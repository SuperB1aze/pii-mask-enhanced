"""Профиль документа: что перед нами - резюме или деловая бумага.

Нужен потому, что одно и то же требование к организациям работает в двух
документах противоположно. Требование правовой формы (ner_org_needs_form)
введено для выгрузок 1С: без него NER метит организациями торговые марки и
удаляет колонку товаров.
"""
from __future__ import annotations

import re

# разделы и обороты, которые вместе встречаются только в резюме и досье по опыту
_MARKERS = (
    "опыт работы", "ключевые компетенции", "профессиональные навыки",
    "карьер", "резюме", "должность", "должности", "обязанности",
    "достижения", "образование", "трудов", "работодател", "вакансия",
    "портфолио", "сопроводительное письмо", "о себе", "занятость",
    "навыки", "стек", "проекты", "курсы", "сертификат", "контакты",
)

# периоды работы: "02.2014 - 01.2025", "2014-2025", "с 2019 по 2023"
_PERIOD_RE = re.compile(
    r"\b(?:\d{2}\.)?(19|20)\d{2}\s*(?:[-–—]|по)\s*(?:\d{2}\.)?(?:(19|20)\d{2}|н\.?в\.?|настоящее)",
    re.IGNORECASE)

# бухгалтерские реквизиты
_PAPER_RE = re.compile(
    r"\b(?:кпп|р/с|к/с|бик|накладная|счет-фактура|платежное поручение"
    r"|книга учета|налогоплательщик)\b", re.IGNORECASE)

# не больше трёх признаков подряд в деловой бумаге
_ENOUGH = 3


# строка контактов в шапке
_CONTACT_LINE_RE = re.compile(
    r"(?:\+7|8)[\d ()\-]{9,}[^\n]{0,80}?[\w.\-]+@[\w.\-]+\.\w{2,}"
    r"|[\w.\-]+@[\w.\-]+\.\w{2,}[^\n]{0,80}?(?:\+7|8)[\d ()\-]{9,}")


def _score(text: str) -> tuple[int, list[str]]:
    low = text.lower()
    hits = sorted(m for m in _MARKERS if m in low)
    score = len(hits)
    periods = len(_PERIOD_RE.findall(text))
    if periods >= 2:
        score += 2
        hits.append(f"периодов работы: {periods}")
    if _CONTACT_LINE_RE.search(text[:1500]):
        score += 1
        hits.append("строка контактов в шапке")
    return score, hits


def looks_like_resume(text: str) -> bool:
    if _PAPER_RE.search(text):
        return False
    score, _ = _score(text)
    return score >= _ENOUGH


def describe(text: str) -> str:
    # логирование
    score, hits = _score(text)
    kind = "резюме" if looks_like_resume(text) else "деловой документ"
    return f"профиль: {kind} (вес {score}: {', '.join(hits[:5]) or 'признаков нет'})"
