"""Профиль документа: что перед нами - резюме или деловая бумага.

Нужен потому, что одно и то же требование к организациям работает в двух
документах противоположно. Требование правовой формы (ner_org_needs_form)
введено для выгрузок 1С: без него NER метит организациями торговые марки и
кромсает колонку товаров. В резюме работодатели пишутся без ООО и без кавычек,
и то же требование оставляет открытыми почти все места работы - замер
28.09.2026 на живом резюме: 3 организации против 62 в мягком режиме.

Определяем грубо и по нескольким признакам сразу: одно слово ничего не значит
("образование" стоит и в уставе), а три вместе - уже резюме. Ошибка в любую
сторону не катастрофична: не узнали резюме - работаем как раньше, приняли
деловую бумагу за резюме - получим лишние маски, но не утечку.
"""
from __future__ import annotations

import re

# Разделы и обороты, которые вместе встречаются только в резюме и досье по опыту.
_MARKERS = (
    "опыт работы", "ключевые компетенции", "профессиональные навыки",
    "карьер", "резюме", "должность", "должности", "обязанности",
    "достижения", "образование", "трудов", "работодател", "вакансия",
    "портфолио", "сопроводительное письмо", "о себе", "занятость",
    # Заголовки коротких резюме без слов "опыт работы": на таком файле детектор
    # промахнулся 28.09.2026, включился строгий режим, и имя кандидата осталось
    # в тексте открытым.
    "навыки", "стек", "проекты", "курсы", "сертификат", "контакты",
)

# Периоды работы: "02.2014 - 01.2025", "2014-2025", "с 2019 по 2023". Признак
# структурный и сильный: в счете и накладной таких диапазонов не бывает, а
# краткое резюме на одну страницу словесных маркеров почти не содержит - на
# живом CV их нашлось два, и одних слов не хватило.
_PERIOD_RE = re.compile(
    r"\b(?:\d{2}\.)?(19|20)\d{2}\s*(?:[-–—]|по)\s*(?:\d{2}\.)?(?:(19|20)\d{2}|н\.?в\.?|настоящее)",
    re.IGNORECASE)

# Бухгалтерская бумага: эти признаки перевешивают. Резюме с расчетным счетом и
# КПП не бывает, а вот счет со словом "должность" в подписи - сплошь и рядом.
_PAPER_RE = re.compile(
    r"\b(?:кпп|р/с|к/с|бик|накладная|счет-фактура|платежное поручение"
    r"|книга учета|налогоплательщик)\b", re.IGNORECASE)

# Два признака подряд бывают и в деловой бумаге, три - уже нет. Периоды работы
# весят как два слова: они точнее любого из них.
_ENOUGH = 3


# Строка контактов в шапке: телефон и почта рядом, часто с ником мессенджера
# или ссылкой на профиль. В деловой бумаге телефон бывает, но связка "телефон
# плюс личная почта в первых строках" - признак резюме.
_CONTACT_LINE_RE = re.compile(
    r"(?:\+7|8)[\d ()\-]{9,}[^\n]{0,80}?[\w.\-]+@[\w.\-]+\.\w{2,}"
    r"|[\w.\-]+@[\w.\-]+\.\w{2,}[^\n]{0,80}?(?:\+7|8)[\d ()\-]{9,}")


def _score(text: str) -> tuple[int, list[str]]:
    low = text.lower()
    hits = sorted(m for m in _MARKERS if m in low)
    score = len(hits)
    periods = len(_PERIOD_RE.findall(text))
    if periods >= 2:
        score += 2
        hits.append(f"периодов работы: {periods}")
    if _CONTACT_LINE_RE.search(text[:1500]):
        score += 1
        hits.append("строка контактов в шапке")
    return score, hits


def looks_like_resume(text: str) -> bool:
    if _PAPER_RE.search(text):
        return False
    score, _ = _score(text)
    return score >= _ENOUGH


def describe(text: str) -> str:
    """Строка для лога: какой профиль выбран и по каким признакам."""
    score, hits = _score(text)
    kind = "резюме" if looks_like_resume(text) else "деловой документ"
    return f"профиль: {kind} (вес {score}: {', '.join(hits[:5]) or 'признаков нет'})"
