"""Именованные наборы: что считать персональными данными в документе.

Набор типов и строгость распознавания - знание про предметную область, а не про
вызывающего. Пока оно жило константами в телеграм-боте, второй потребитель
услуги подбирал бы те же шестнадцать типов и четыре флага заново и получил бы
на том же файле другой результат - причем молча, оба прогона отвечают кодом 0.

Наборов два, и различает их строгость к организациям, а не список типов.
Список общий: расчетного счета в резюме не бывает, а если встретится -
маскировать его правильно; недостающий тип стоит пропуска ПД.
"""
from __future__ import annotations

from dataclasses import dataclass

# REQ ("реквизит документа") из DEFAULT_TYPES намеренно исключен: в КУДиР под
# него попадает номер первичного документа ("№ 4"), а это не ПД, а ссылка, без
# которой книгу не сверить с первичкой. На живой выгрузке дефолтный набор дал
# 152 сущности против 79, и вся разница - номера.
#
# Остальное набиралось по разбору живых файлов за сентябрь 2026: ADDRESS (у ИП
# в графе адреса домашний), KPP и DOCREF (по паре номер-дата сделка опознается
# целиком), DATE - только внутри ссылки на документ, CERT и UID (опознают
# подписанта), BIK и ACCOUNT (счет опознает предпринимателя не хуже ИНН), TG и
# URL (ник и ссылка на профиль работодателя опознают человека вернее почты).
TYPES = (
    "PERSON", "ORG", "INN", "OGRN", "KPP", "BIK", "ACCOUNT", "PHONE", "EMAIL",
    "ADDRESS", "DOCREF", "DATE", "CERT", "UID", "TG", "URL",
)


@dataclass(frozen=True)
class Preset:
    name: str
    title: str
    types: tuple[str, ...]
    ner_org_needs_form: bool
    # Человека от NER принимаем, только если спан похож на ФИО: иначе в люди
    # уходит товарная номенклатура ("Экософт", "Пентек", "Карбонблок").
    ner_person_needs_fio: bool = True
    # Голый десятизначный номер с валидной контрольной суммой неотличим от
    # артикула, а сумму случайное число проходит примерно раз из одиннадцати.
    inn_needs_label: bool = True


_PRESETS = {
    "accounting": Preset(
        name="accounting",
        title="деловая бумага (счета, акты, выгрузки 1С)",
        types=TYPES,
        # Контрагент в бухгалтерском документе всегда с правовой формой, а
        # торговая марка - никогда. Без этого требования "Grand Forest" и
        # "NatureWater" уходят в маски, и колонка товаров приходит искромсанной.
        ner_org_needs_form=True,
    ),
    "resume": Preset(
        name="resume",
        title="резюме и досье по опыту",
        types=TYPES,
        # То же требование на резюме работает наоборот: работодатели пишутся
        # без ООО и без кавычек. Замер 28.09.2026 на живом файле - 3
        # организации против 62.
        ner_org_needs_form=False,
    ),
}

AUTO = "auto"


def names() -> list[str]:
    return sorted(_PRESETS)


def get(name: str) -> Preset:
    try:
        return _PRESETS[name]
    except KeyError:
        raise ValueError(
            f"набор {name!r} не знаю; есть: {', '.join(names())} и "
            f"{AUTO} (выбрать по документу)") from None


def resolve(name: str, probe: str | None) -> tuple[Preset, str]:
    """Набор и человеческая причина выбора - ее печатает CLI в stderr.

    Причина обязательна: без нее два прогона одного файла необъяснимо дают
    разный результат, а смена режима ничем себя не выдает.
    """
    if name != AUTO:
        chosen = get(name)
        return chosen, f"набор: {chosen.name} - {chosen.title}"

    from . import profile

    if probe is None:
        # Лишняя маска дешевле пропуска, поэтому неизвестность - строгий режим.
        return _PRESETS["accounting"], (
            "набор: accounting - профиль определить не удалось, "
            "остаюсь в строгом режиме")
    chosen = _PRESETS["resume" if profile.looks_like_resume(probe) else "accounting"]
    return chosen, f"набор: {chosen.name} - {profile.describe(probe)}"
