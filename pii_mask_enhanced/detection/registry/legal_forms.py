"""Правовые формы организаций: один список на все распознаватели."""
from __future__ import annotations

SHORT = ("АО", "ОАО", "ЗАО", "ПАО", "НАО", "ООО", "НКО", "АНО", "ПК", "ГК",
         "ФГУП", "ГУП", "МУП", "ФГБУ", "ИП")
FULL = (r"Акционерное\s+общество", r"Публичное\s+акционерное\s+общество",
        r"Общество\s+с\s+ограниченной\s+ответственностью")
# слова, которые сами указывают на организацию
GENERIC = ("Банк", "Компания", "Бюро", "Фонд")

# ПК и ГК - еще "компьютер" и "Гражданский кодекс": формой они бывают только перед кавычками
_AMBIGUOUS = ("ПК", "ГК")


def _alt(words) -> str:
    return "(?:" + "|".join(words) + ")"


# форма перед названием: 'ООО "Ромашка"', "Банк «Север»"
ORG_FORM = _alt(SHORT + FULL + GENERIC)
# форма в ячейке книги: по ней видно контрагента
CELL_FORM = _alt(f for f in SHORT if f not in _AMBIGUOUS)
# форма после названия: "Василек Технологии, ЗАО" (hh.ru); ИП так не пишут
TRAILING_FORM = _alt(f for f in SHORT if f not in _AMBIGUOUS and f != "ИП")
