"""Документы личности и транспорта: формат номера и слова, по которым документ узнается.

Паспорт РФ сюда не входит - у него свой тип PASSPORT. Новый документ - новая запись.
"""
from __future__ import annotations

from dataclasses import dataclass

# между серией и номером: пробел или "№"
_SEP = r"(?:[ \t]*№[ \t]*|[ \t]+)"
# римские цифры серии; Х и І бывают кириллицей
_ROMAN = r"[IVXІХ]{1,4}"
_LETTERS = r"[А-ЯЁ]{2}"

# Форматы номеров, общие для нескольких документов
# серия 2 цифры, номер 7: "82 № 1234567"
_DIGITS_2_7 = rf"\d{{2}}{_SEP}\d{{7}}"
# серия 2 буквы, номер 7: "АБ 1234567"
_LETTERS_2_7 = rf"{_LETTERS}{_SEP}\d{{7}}"
# Между серией и номером бывает слово: "серия 77 УО номер 123456"
_SERIES_SEP = rf"(?:{_SEP}|[ \t]+[Нн]омер[ \t]*(?:№[ \t]*)?)"
# Документы на машину и водителя
_VEHICLE = rf"\d{{2}}[ \t]?(?:\d{{2}}{_SERIES_SEP}|{_LETTERS}{_SERIES_SEP}?)\d{{6}}"
_PTS = rf"\d{{2}}[ \t]?{_LETTERS}{_SERIES_SEP}?\d{{6}}"
# "ТС" - только заглавными: "тс" бывает и междометием
_TS = r"(?:(?-i:ТС)(?!\w)|транспортн\w*)"
# серия - код региона
_PERMIT = rf"\d{{2}}{_SEP}\d{{7,10}}"
# Диплом: с 2014 - серия 6 цифр и номер 7 "107724 0123456"; до 2014 - буквы "ВСГ 1234567",
# "ЭВ 123456"
_DIPLOMA = rf"\d{{6}}{_SERIES_SEP}\d{{7}}|[А-ЯЁ]{{2,3}}{_SERIES_SEP}\d{{6,7}}"
# Аттестат: с 2014 - 14 цифр слитно; 2008-2013 - регион и буквы "05 АБ 0123456";
# до 2008 - одна буква "А 1234567"
_ATTESTAT = (rf"\d{{14}}|\d{{2}}[ \t]?{_LETTERS}{_SERIES_SEP}\d{{7}}"
             rf"|[А-ЯЁ]{_SERIES_SEP}\d{{7}}")


@dataclass(frozen=True)
class IdDoc:
    name: str
    # номер - с учетом регистра
    number: str
    # слова документа
    context: str | None = None
    # только для форматов, которые не совпадают с паспортом РФ
    whole_doc: bool = False
    # слово документа должно стоять прямо перед номером, а не где-то рядом
    # ("виза руководителя", "патент на изобретение")
    tight: bool = False


DOCS = (
    IdDoc("загранпаспорт", rf"{_DIGITS_2_7}|\d{{9}}",
          r"загран\w*|заграничн\w*|для[ \t]+выезда", whole_doc=True),
    IdDoc("военный билет", _LETTERS_2_7,
          r"военн\w*[ \t]+билет\w*|в/б(?!\w)", whole_doc=True),
    IdDoc("водительское удостоверение", _VEHICLE, r"водительск\w*|(?-i:ВУ)(?!\w)"),
    # о рождении, смерти, браке: "IV-МЮ 123456"
    IdDoc("свидетельство ЗАГС", rf"{_ROMAN}[-–]{_LETTERS}{_SEP}\d{{6}}"),
    IdDoc("СТС", _VEHICLE,
          rf"(?-i:СТС)(?!\w)|свидетельств\w*[ \t]+о[ \t]+регистрации[ \t]+{_TS}"),
    # ЭПТС - 15 цифр
    IdDoc("ПТС", rf"{_PTS}|\d{{15}}",
          rf"(?-i:Э?ПТС)(?!\w)|(?:электронн\w*[ \t]+)?паспорт\w*[ \t]+{_TS}"),
    IdDoc("паспорт моряка", _LETTERS_2_7,
          r"паспорт\w*[ \t]+моряк\w*|удостоверени\w*[ \t]+личности[ \t]+моряк\w*", whole_doc=True),
    # "ТК-IV 1234567", старый образец "АТ-IX 1234567", вкладыш "ВТ-I"
    IdDoc("трудовая книжка", rf"{_LETTERS}[-–]{_ROMAN}{_SEP}\d{{7}}"),
    IdDoc("вид на жительство", _DIGITS_2_7,
          r"вид\w*[ \t]+на[ \t]+жительств\w*|(?-i:ВНЖ)(?!\w)", whole_doc=True),
    IdDoc("разрешение на временное проживание", _DIGITS_2_7,
          r"разрешени\w*[ \t]+на[ \t]+временн\w*[ \t]+проживани\w*|(?-i:РВП)(?!\w)",
          whole_doc=True),
    IdDoc("разрешение на работу", _PERMIT, r"разрешени\w*[ \t]+на[ \t]+работ\w*", whole_doc=True),
    IdDoc("патент на работу", _PERMIT, r"патент\w*", tight=True),
    IdDoc("миграционная карта", rf"\d{{4}}{_SEP}\d{{7}}",
          r"миграционн\w*[ \t]+карт\w*", whole_doc=True),
    IdDoc("виза", rf"{_DIGITS_2_7}|\d{{9}}", r"виз(?:а|ы|е|у|ой)(?!\w)|(?-i:visa)", tight=True),
    # Документы об образовании
    IdDoc("диплом", _DIPLOMA,
          r"диплом\w*(?:[ \t]+(?:о[ \t]+(?:высшем|среднем[ \t]+профессиональном"
          r"|профессиональн\w*[ \t]+переподготовк\w*)(?:[ \t]+образовании)?"
          r"|бакалавр\w*|специалист\w*|магистр\w*))?"),
    # одна буква "А 1234567" - только сразу за словом аттестата
    IdDoc("аттестат", _ATTESTAT,
          r"аттестат\w*(?:[ \t]+о[ \t]+(?:среднем|основном)(?:[ \t]+(?:общем|полном))?"
          r"(?:[ \t]+общем)?[ \t]+образовании)?", tight=True),
)
