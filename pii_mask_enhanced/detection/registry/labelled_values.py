"""Значения, которые узнаются только по подписи: "ЕСИА ID: 1000123456", "пол: жен."
"""
from __future__ import annotations

from dataclasses import dataclass


def _digits(lo: int, hi: int) -> str:
    # цифры могут идти группами: полис "7700 0000 0000 0000"
    return rf"\d(?:[ -]?\d){{{lo - 1},{hi - 1}}}(?!\d)"


# код с хотя бы одной цифрой: "обращение № 2024-0012345", "таб. № А-0123"
_CODE = r"(?=[\w./-]*\d)\w(?:[\w/-]|\.(?=\w)){1,39}(?![\w/-])"
# до четырех слов: "Республика Беларусь", "не замужем"; кончается на знаке препинания
_WORDS = r"[^\W\d_][\w-]*(?:[ \t]+[^\W\d_][\w-]*){0,3}"
# страна: одно слово или устойчивое из двух
_COUNTRY = (r"(?:РФ|Российск\w*[ \t]+Федераци\w*|Республик\w*[ \t]+[А-ЯЁ][\w-]*"
            r"|[А-ЯЁA-Z][\w-]*)")
# до конца строки, широкой отбивки или границы колонки
_TO_LINE_END = r"[^\n|]*?[^\s|](?=[ \t]*(?:\n|$|\||[ \t]{3}))"

# Банковский счет: "р/с", "к/сч", "Сч.", "номер счета", "расчетный счет", "корр.счет",
# "счет получателя". "/" перед подписью - часть другой: "ИНН/КПП/к/с"
_ACCOUNT_LABEL = (
    r"(?<!/)(?:[ркл]/сч?"
    r"|(?:номер[ \t]+)?(?:(?:расч|корр|лицев|банковск|текущ|сберегат|депозитн)\w*\.?[ \t]*)?"
    r"сч[её]т\w*(?:[ \t]+(?:получател|плательщик|клиент|организаци|банк)\w*)?"
    r"|сч\.?)"
)
# 20 цифр слитно или группами: "4081 7810 0999 1000 4312", "40817.810.0.9991.0004312"
_ACCOUNT_NUM = r"\d(?:[ .\-]?\d){19}(?!\d)(?![.\-]\d)"

# Код инвестора: формат свой у каждого брокера и биржи. "код" - целым словом в падежах
_KOD = r"код(?:а|у|ом|ы|ов)?(?!\w)"
_INVESTOR_LABEL = (
    rf"(?:УКК|уникальн\w*[ \t]+{_KOD}(?:[ \t]+клиент\w*)?"
    rf"|торгов\w*[ \t]+{_KOD}(?:[ \t]+клиент\w*)?"
    rf"|{_KOD}[ \t]+(?:инвестор|клиент)\w*|клиентск\w*[ \t]+{_KOD})"
    rf"(?:[ \t]*\([^)\n]{{1,20}}\))?(?:[ \t]+[^\W\d_]+){{0,3}}?"
)

_INVESTOR_CODE = (r"(?=[\w/+.-]*\d)[A-Za-zА-Яа-яЁё0-9](?:[\w/+-]|\.(?=[\w/+-])){2,24}"
                  r"(?!\.?[\w/+-])")

# Орган выдачи: подпись поля анкеты однозначна
_ISSUER_LABEL = (r"кем[ \t]+выдан\w*"
                 r"|(?:наименовани\w*[ \t]+)?орган\w*,?[ \t]+выдавш\w+[ \t]+(?:документ|паспорт)\w*")
_ISSUER_NAME = r"(?=[^\n,;|]*[А-ЯЁA-Z])[^\n,;|]*?[^\s,;|.](?=[ \t.]*(?:\n|$|[,;|]|[ \t]{3}))"
# подпись кода подразделения; ей же engine/propagation заканчивает орган после "выдан"
UNIT_CODE_LABEL = r"код\w*[ \t]+подр(?:азделени\w*|\.)"


@dataclass(frozen=True)
class LabelledValue:
    name: str
    type: str
    # подпись
    label: str
    # значение за подписью; регистр важен
    value: str
    # подпись должна кончаться на ":" или "="
    needs_sep: bool = False
    # ключ по цифрам: счет слитно и группами - одно значение, одна метка
    digits_key: bool = False


VALUES = (
    LabelledValue("банковский счет", "ACCOUNT", _ACCOUNT_LABEL, _ACCOUNT_NUM, digits_key=True),
    # без подписи узнается только торговый код Мосбиржи (regulars.MOEX_CODE_RE)
    LabelledValue("код инвестора", "INVESTOR", _INVESTOR_LABEL, _INVESTOR_CODE),

    # идентификатор человека в чужой системе
    LabelledValue("ЕСИА ID", "PERSON_ID",
                  r"(?:ЕСИА|госуслуг\w*)(?:[ \t]+(?:ID|идентификатор\w*))?", _digits(5, 15)),
    LabelledValue("MDM ID", "PERSON_ID", r"MDM(?:[ \t]*(?:ID|ид\w*))?", _CODE),
    LabelledValue("табельный номер", "PERSON_ID", r"таб(?:ельн\w*|\.)?[ \t]*(?:номер|№)", _CODE),
    LabelledValue("логин", "PERSON_ID", r"логин|login|user[ _-]?name|имя[ \t]+пользователя",
                  # точка - только внутри: "логин: ivanov_i." - конец предложения
                  r"[\w@+-](?:[\w@+-]|\.(?=[\w@+-])){2,63}", needs_sep=True),
    LabelledValue("номер обращения", "PERSON_ID", r"обращени\w*[ \t]*№", _CODE),
    LabelledValue("карта лояльности", "PERSON_ID",
                  r"карт\w*[ \t]+(?:лояльност\w*|клиент\w*|бонусн\w*|скидочн\w*|«[^»\n]{1,20}»)",
                  _CODE),
    # ОСАГО с буквенной серией: "ХХХ 0123456789"
    LabelledValue("полис", "PERSON_ID", r"полис\w*(?:[ \t]+(?:ОМС|ДМС|ОСАГО|КАСКО))?",
                  rf"(?:[А-ЯЁA-Z]{{3}}[ \t]?)?{_digits(9, 16)}"),
    LabelledValue("ЭЛН", "PERSON_ID",
                  r"ЭЛН|лист(?:ок|к\w*)[ \t]+нетрудоспособност\w*|больничн\w*(?:[ \t]+лист\w*)?",
                  r"\d{12}(?!\d)"),
    LabelledValue("счет депо", "PERSON_ID", r"(?:раздел\w*[ \t]+)?сч[её]т\w*[ \t]+депо", _CODE),

    # секреты: по ним входят в систему или подтверждают личность
    LabelledValue("CVV", "SECRET",
                  r"CVV2?|CVC2?|CAV2|CID|код\w*[ \t]+(?:безопасности|на[ \t]+оборот\w*)",
                  r"\d{3,4}(?!\d)"),
    LabelledValue("PIN", "SECRET", r"(?:PIN|ПИН)(?:[ -]?код)?", r"\d{4,6}(?!\d)"),
    LabelledValue("пароль", "SECRET", r"пароль|password|passwd|pwd", r"[^\s,;]{3,64}",
                  needs_sep=True),
    LabelledValue("кодовое слово", "SECRET", r"кодов\w*[ \t]+слов\w*", _TO_LINE_END),

    # сведения о человеке
    # "пол" - и пол комнаты, поэтому двоеточие обязательно
    LabelledValue("пол", "PERSONAL", r"пол",
                  r"(?:[Мм]уж\w*|[Жж]ен\w*|[МмЖж]|[Mm]ale|[Ff]emale|[MF])\.?(?!\w)", needs_sep=True),
    # после двоеточия - любое значение, без него - только название
    LabelledValue("гражданство", "PERSONAL", r"гражданств\w*", _WORDS, needs_sep=True),
    LabelledValue("гражданство без двоеточия", "PERSONAL", r"гражданств\w*|граждан(?:ин|ка)",
                  rf"{_COUNTRY}(?!\w)"),
    LabelledValue("семейное положение", "PERSONAL", r"семейн\w*[ \t]+положени\w*", _WORDS,
                  needs_sep=True),
    LabelledValue("возраст", "PERSONAL", r"возраст\w*",
                  r"\d{1,3}(?:[ \t]*(?:лет|год\w*))?(?!\w)"),
    LabelledValue("ПКР", "PERSONAL",
                  r"ПКР|(?:персональн\w*[ \t]+)?кредитн\w*[ \t]+рейтинг\w*", r"\d{1,4}(?!\d)"),

    # назначение платежа: рассказывает, кто, кому и за что платил
    LabelledValue("назначение платежа", "PAYMENT", r"назначени\w*[ \t]+платеж\w*",
                  _TO_LINE_END),

    # орган выдачи документа; после "выдан" за номером его разбирает engine/propagation
    LabelledValue("орган выдачи", "ISSUER", _ISSUER_LABEL, _ISSUER_NAME),
    LabelledValue("код подразделения", "ISSUER", UNIT_CODE_LABEL, r"\d{3}[ \t-]?\d{3}(?!\d)",
                  digits_key=True),
)
