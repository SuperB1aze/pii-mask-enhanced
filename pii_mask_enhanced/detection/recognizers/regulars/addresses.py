"""Адреса и место жительства."""
import re

from .. import helpers

ADDRESS_RE = re.compile(
    rf"(?:\d{{6}},?{helpers.WRAP})?{helpers.ADDR_REGION}{helpers.ADDR_DISTRICT}{helpers.ADDR_CITY}"
    rf"(?<![А-Яа-яЁё]){helpers.ADDR_HEAD},?{helpers.WRAP}{helpers.ADDR_TAIL}",
    re.IGNORECASE,
)
# "д.35, кв.47" без улицы: улицу по фамилии NER мог забрать как персону
ADDRESS_TAIL_RE = re.compile(
    rf"(?<![А-Яа-яЁё])д(?:ом)?\.?{helpers.WRAP}\d+[А-Яа-я]?[,\s]*кв\w*\.?{helpers.WRAP}\d+",
    re.IGNORECASE
)

_AFTER_INDEX = (r"(?=[А-ЯЁA-Z][а-яёa-z]"
                r"|(?:г|гор|пос|пгт|с|дер|рп|ул|д|обл|респ|р-н|пр-кт|пер|наб|ш|мкр)\.)")
ADDRESS_RUN_RE = re.compile(
    rf"(?<!\d)\d{{6}},[ \t]?{_AFTER_INDEX}(?:[^\n]{{0,120}}?)(?=\n|[ \t]{{3,}}|$)",
)

# индекс, за которым в 60 знаках идут регион или улица ("г." не признак - это и "год")
ADDRESS_INDEX_RE = re.compile(
    rf"(?<!\d)\d{{6}}(?=,[\s\S]{{0,60}}?"
    rf"(?:обл\.|область|край\b|респ\w*\.|округ|р-н|ул\.|улиц|пр-кт|просп|пер\.|шоссе))",
    re.IGNORECASE,
)

# Населенный пункт по слову перед ним: "г. Тверь", "в городе Ростов-на-Дону", "с. Иваново".
# "2020 г. Москва" - год; "ст." - и статья, его нет
_PLACE_KIND = (r"(?i:(?:г|гор|пос|дер|с|рп)\.|пгт\.?|ст-ца|город(?:а|е|у|ом)?"
               r"|пос[её]л(?:ок|ка|ке|ком)|деревн(?:я|и|е|ю|ей)|сел(?:о|а|е|ом)"
               r"|станиц(?:а|ы|е|у|ей))")
# "Ростов-на-Дону", "Санкт-Петербург"; второе слово - за прилагательным: "Нижний Новгород"
_PLACE = (r"[А-ЯЁ][а-яё]+(?:-[а-яё]+)*(?:-[А-ЯЁ][а-яё]+)?"
          r"(?:(?<=[иыо]й|ая|ое|[иы]е|ем)[ \t][А-ЯЁ][а-яё]+)?")
# "ИФНС по г. Твери", "ОУФМС России по г. Москве" - территория ведомства, а не место человека
CITY_RE = re.compile(rf"(?<![\w.])(?<!\d)(?<!\d[ \t])(?<!\bпо[ \t])"
                     rf"{_PLACE_KIND}[ \t]?({_PLACE})(?![\w-])")

# Регион: "Тверская область", "Пермский край", "Кировский р-н", "Республика Татарстан".
# Прилагательное на -ск-/-цк-: "Предметная область" - не регион
REGION_RE = re.compile(
    r"(?<![\w-])(?:[А-ЯЁ][а-яё]*(?:-[А-ЯЁ][а-яё]+)?(?:ск|цк)[а-яё]{2,3}[ \t]+"
    r"(?i:автономн\w*[ \t]+(?:округ|област)\w*|обл(?:аст(?:ь|и|ью))?\.?|кра(?:й|я|ю|ем|е)"
    r"|район(?:а|е|у|ом)?|р-н(?:а|е)?|округ(?:а|е|у|ом)?)"
    r"|(?i:респ(?:ублик(?:а|и|е|у|ой))?\.?)[ \t]+[А-ЯЁ][а-яё]+(?:[ \t-][А-ЯЁ][а-яё]+)?)"
    r"(?![\w-])")

CITIZENSHIP_BEFORE_RE = re.compile(r"гражданств\w*[ \t]*[:\-–—]?[ \t]*$", re.IGNORECASE)

# Улица без "ул." и дом без "д.": "Ленина, 5, кв. 12", "Ленина 5/1, кв. 3" - квартира
# обязательна, иначе это "Глава 5"; после населенного пункта хватает дома: "г. Тверь, Ленина 5-12"
_HOUSE = r"\d{1,4}[а-яА-Я]?(?:[ \t]*(?:/|,?[ \t]*(?:корп|стр|к)\.?[ \t]*)\d{1,3}[а-яА-Я]?)?"
_STREET_NAME = r"[А-ЯЁ][а-яё]+(?:[ \t-][А-ЯЁ][а-яё]+)?"
STREETLESS_RE = re.compile(
    rf"(?<![\w-]){_STREET_NAME},?[ \t]+{_HOUSE},?[ \t]*(?i:кв(?:артира|\.)?)[ \t]*\d{{1,4}}(?!\d)"
    rf"|{_PLACE_KIND}[ \t]?{_PLACE},[ \t]*{_STREET_NAME},?[ \t]+{_HOUSE}"
    rf"(?:-\d{{1,4}}|,?[ \t]*(?i:кв(?:артира|\.)?)[ \t]*\d{{1,4}})?(?![\d\w])"
)

# Координаты. Десятичная пара "55.7558, 37.6173": без подписи - только с 4+ знаками
# после точки (проверка в finders/addresses); градусы - со стороной света: "55°45′N", "55° с.ш."
COORD_PAIR_RE = re.compile(
    r"(?<![\w.,-])([-−]?\d{1,2}\.(\d{2,8}))°?(?:[ \t]?[NSСЮ](?!\w))?"
    r"(?:[ \t]*[,;][ \t]*|[ \t]+)([-−]?\d{1,3}\.(\d{2,8}))°?(?:[ \t]?[EWВЗ](?!\w))?(?![\w.]|,\d)")
COORD_DEG_RE = re.compile(
    r"(?<![\w.])(?:([NSEW])[ \t]?)?\d{1,3}°[ \t]?"
    r"(?:\d{1,2}(?:[.,]\d+)?['′][ \t]?(?:\d{1,2}(?:[.,]\d+)?(?:[\"″]|'')[ \t]?)?)?"
    r"((?:[NSEW]|[сю]\.?[ \t]?ш\.|[вз]\.?[ \t]?д\.)(?![\w]))?")
COORD_LABEL_RE = re.compile(
    r"координат\w*|GPS|геолокаци\w*|геопозици\w*|местоположени\w*|широт\w*|долгот\w*"
    r"|\bgeo\w*|\blat(?:itude)?\b|\blo?ng?(?:itude)?\b|location",
    re.IGNORECASE)

RESIDENCE_RE = re.compile(
    r"(?:проживает|проживание|город проживания|место жительства|город)\s*[:\-]\s*"
    r"([А-ЯЁ][а-яё]+(?:[ -][А-ЯЁ][а-яё]+){0,2})",
    re.IGNORECASE)
