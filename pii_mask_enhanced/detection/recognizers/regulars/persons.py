"""Люди: ФИО капсом и с инициалами, дата и год рождения."""
import re

from ...registry.labelled_values import PERSON_TERMS
from .. import helpers

CAPS_FIO_RE = re.compile(
    rf"(?<![А-ЯЁ\w])(?:"
    # ФАМИЛИЯ ИМЯ ОТЧЕСТВО, фамилия может быть двойной
    rf"{helpers.CAPS_WORD}{helpers.FIO_SEP}(?:{helpers.CAPS_WORD}{helpers.FIO_SEP})?{helpers.CAPS_WORD}{helpers.FIO_SEP}{helpers.CAPS_PATR}"
    rf"|{helpers.CAPS_WORD}{helpers.FIO_SEP}{helpers.CAPS_PATR}{helpers.FIO_SEP}{helpers.CAPS_WORD}"  # ИМЯ ОТЧЕСТВО ФАМИЛИЯ
    rf"|{helpers.CAPS_WORD}{helpers.FIO_SEP}{helpers.CAPS_PATR}"                        # ИМЯ ОТЧЕСТВО
    rf")(?![А-ЯЁ\w])"
)

CAPS_PATR_RE = re.compile(rf"(?<![А-ЯЁ\w])[А-ЯЁ]{{3,}}{helpers.PATR_TAIL}(?![А-ЯЁ\w])")

INITIALS_RE = re.compile(
    rf"(?<![А-ЯЁ\w]){helpers.SURNAME}[ \t]+[А-ЯЁ]\.[ \t]?[А-ЯЁ]\.(?!\w)"
    rf"|(?<![А-ЯЁ\w])[А-ЯЁ]\.[ \t]?[А-ЯЁ]\.[ \t]?{helpers.SURNAME}(?![А-ЯЁ\w])"
)

# только дата рождения; прочие даты не трогаем
BIRTH_DATE_RE = re.compile(
    r"(?:родил(?:ся|ась)|дата\s+рожд\w*\.?\s*[:\-]?|д\.?\s?р\.?\s*[:\-]?)\s*"
    rf"({helpers.DATE})",
    re.IGNORECASE)
# Дата смерти
DEATH_DATE_RE = re.compile(
    r"(?<!\w)(?:умер(?:ла)?|скончал(?:ся|ась)|погиб(?:ла)?|ум\.|"
    r"дат\w*\s+(?:смерти|кончины|гибели)\.?\s*[:\-]?)\s*"
    rf"(?:\s*в\s+)?({helpers.DATE})",
    re.IGNORECASE)
DEATH_YEAR_RE = re.compile(
    r"(?<!\w)(?:год\w*\s+(?:смерти|кончины|гибели)|умер(?:ла)?\s+в|скончал(?:ся|ась)\s+в"
    r"|погиб(?:ла)?\s+в)\s*[:\-]?\s*((?:19|20)\d{2})(?!\d)",
    re.IGNORECASE)

# Судимость и преследование (ст. 10 152-ФЗ). Статья кодекса - ПД только при слове о
# преследовании рядом: "осужден по ч. 2 ст. 159 УК РФ". Сама по себе - текст закона:
# "ст. 159 УК РФ предусматривает..."
_ARTICLE_PART = r"(?:ч(?:аст\w*|\.)?|п(?:ункт\w*|\.)?)[ \t]*(?:«[а-я]»|\"[а-я]\"|[а-я]\)|\d+)"
CRIMINAL_ARTICLE_RE = re.compile(
    rf"(?<!\w)(?:{_ARTICLE_PART}(?:[ \t]*,[ \t]*\d+)*[ \t]+){{0,3}}"
    r"ст(?:ать\w*|\.)?[ \t]*\d+(?:\.\d+)?(?:[ \t]*(?:,|и)[ \t]*\d+(?:\.\d+)?)*"
    r"[ \t]+(?:УК|УПК|КоАП|Уголовного[ \t]+кодекса)(?:[ \t]+(?:РФ|Российской[ \t]+Федерации))?",
    re.IGNORECASE)
# слово о преследовании человека - в той же строке, рядом со статьей (finders/persons)
CRIMINAL_TRIGGER_RE = re.compile(
    # "судимость" - и понятие из закона ("понятие судимости в ст. 86 УК РФ"): только про человека
    r"осужд\w*|обвин\w*|подозрева\w*|судим(?:а|ый|ая|ые|ого|ой)?(?!\w)|приговор\w*"
    r"|отбыва\w*|отбыл\w*"
    r"|привлеч\w*|привлека\w*|возбужд\w*[ \t]+(?:уголовн|административн)\w*"
    r"|признан\w*[ \t]+виновн\w*|задержан\w*|арестован\w*|освобожд[её]н\w*",
    re.IGNORECASE)
CRIMINAL_WINDOW = 80
# устойчивые обороты о судимости - ПД сами по себе: про кого-то конкретного
CRIMINAL_STATUS_RE = re.compile(
    r"(?<!\w)(?:ранее[ \t]+(?:не[ \t]+)?судим(?:а|ый|ая)?|не[ \t]+судим(?:а|ый|ая)?"
    r"|(?:не[ \t]+)?имеет[ \t]+(?:непогашенн\w*[ \t]+)?судимост\w*"
    r"|судимост\w*[ \t]+(?:погашен\w*|снят\w*|не[ \t]+имеет\w*)"
    r"|(?:не[ \t]+)?привлекал(?:ся|ась)[ \t]+к[ \t]+уголовн\w*[ \t]+ответственност\w*)(?!\w)",
    re.IGNORECASE)

# звание, степень, семейное положение, возраст - рядом с найденным ФИО (engine/propagation)
PERSON_TERMS_RE = re.compile(
    "|".join(rf"(?<!\w)(?:{t})(?!\w)" for t in PERSON_TERMS), re.IGNORECASE)
# сколько знаков до и после ФИО считается "рядом"; дальше строки окно не идет
PERSON_TERMS_WINDOW = 50

# год рождения: "1985 г.р.", "г.р. 1985"; точка обязательна, иначе "500 гр" - граммы
BIRTH_YEAR_RE = re.compile(
    r"(?<!\d)((?:19|20)\d{2})[ \t]*г\.[ \t]?р\.?(?!\w)"
    r"|(?<!\w)г\.[ \t]?р\.[ \t]*((?:19|20)\d{2})(?!\d)",
    re.IGNORECASE)
