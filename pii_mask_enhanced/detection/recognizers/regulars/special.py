"""Специальные категории (ст. 10 152-ФЗ) и сведения рядом с ними: судимость, здоровье,
допуск к гостайне и классный чин, доля в капитале."""
import re

# Судимость и преследование (ст. 10 152-ФЗ). Статья кодекса - ПД только при слове о
# преследовании рядом: "осужден по ч. 2 ст. 159 УК РФ". Сама по себе - текст закона:
# "ст. 159 УК РФ предусматривает..."
_ARTICLE_PART = r"(?:ч(?:аст\w*|\.)?|п(?:ункт\w*|\.)?)[ \t]*(?:«[а-я]»|\"[а-я]\"|[а-я]\)|\d+)"
CRIMINAL_ARTICLE_RE = re.compile(
    rf"(?<!\w)(?:{_ARTICLE_PART}(?:[ \t]*,[ \t]*\d+)*[ \t]+){{0,3}}"
    r"ст(?:ать\w*|\.)?[ \t]*\d+(?:\.\d+)?(?:[ \t]*(?:,|и)[ \t]*\d+(?:\.\d+)?)*"
    r"[ \t]+(?:УК|УПК|КоАП|Уголовного[ \t]+кодекса)(?:[ \t]+(?:РФ|Российской[ \t]+Федерации))?",
    re.IGNORECASE)
# слово о преследовании человека - в той же строке, рядом со статьей (finders/special)
CRIMINAL_TRIGGER_RE = re.compile(
    # "судимость" - и понятие из закона ("понятие судимости в ст. 86 УК РФ"): только про человека
    r"осужд\w*|обвин\w*|подозрева\w*|судим(?:а|ый|ая|ые|ого|ой)?(?!\w)|приговор\w*"
    r"|отбыва\w*|отбыл\w*"
    r"|привлеч\w*|привлека\w*|возбужд\w*[ \t]+(?:уголовн|административн)\w*"
    r"|признан\w*[ \t]+виновн\w*|задержан\w*|арестован\w*|освобожд[её]н\w*",
    re.IGNORECASE)
CRIMINAL_WINDOW = 80
# устойчивые обороты о судимости - ПД сами по себе: про кого-то конкретного
CRIMINAL_STATUS_RE = re.compile(
    r"(?<!\w)(?:ранее[ \t]+(?:не[ \t]+)?судим(?:а|ый|ая)?|не[ \t]+судим(?:а|ый|ая)?"
    r"|(?:не[ \t]+)?имеет[ \t]+(?:непогашенн\w*[ \t]+)?судимост\w*"
    r"|судимост\w*[ \t]+(?:погашен\w*|снят\w*|не[ \t]+имеет\w*)"
    r"|(?:не[ \t]+)?привлекал(?:ся|ась)[ \t]+к[ \t]+уголовн\w*[ \t]+ответственност\w*)(?!\w)",
    re.IGNORECASE)

# Здоровье
_ICD_CODE = r"[A-TV-ZАВСЕКМНОРТХ]\d{2}(?:\.\d{1,2})?(?![\w.])"
ICD_RE = re.compile(
    r"(?<!\w)(?:диагноз\w*|д-?з\.?|(?-i:Ds|DS)|(?:код|шифр)\w*[ \t]+(?:по[ \t]+)?МКБ(?:-?10)?|МКБ(?:-?10)?)"
    rf"[ \t]*[:.]?[ \t]*({_ICD_CODE}(?:[ \t]*[,;][ \t]*{_ICD_CODE})*)",
    re.IGNORECASE)
# инвалидность и ограничения
_DIS_GROUP = r"(?:I{1,3}|[123])(?:-?(?:й|я|ей))?"
DISABILITY_RE = re.compile(
    rf"(?<!\w)(?:инвалид\w*[ \t]+{_DIS_GROUP}[ \t]+групп\w*"
    rf"|{_DIS_GROUP}[ \t]+групп\w*[ \t]+инвалидност\w*"
    rf"|групп\w*[ \t]+инвалидност\w*[ \t]*[:\-]?[ \t]*{_DIS_GROUP}"
    r"|реб[её]н\w*-инвалид\w*|инвалид\w*[ \t]+детства"
    r"|(?:степен\w*[ \t]+)?ограничени\w*[ \t]+(?:трудоспособност|жизнедеятельност)\w*"
    r"(?:[ \t]+(?:I{1,3}|[123])(?:-?(?:й|я|ей))?[ \t]+степен\w*)?)(?!\w)",
    re.IGNORECASE)

# Допуск к гостайне и классный чин гражданской службы
_FORM_NUM = r"(?:[123]|I{1,3}|перв\w*|втор\w*|трет\w*)(?:-?(?:й|я|ой|ая))?"
CLEARANCE_RE = re.compile(
    rf"(?<!\w)(?:форм\w*[ \t]+допуска[ \t]*(?:[:№][ \t]*)?{_FORM_NUM}"
    rf"|допуск\w*[ \t]+(?:по[ \t]+)?{_FORM_NUM}[ \t]+форм\w*"
    r"|допуск\w*[ \t]+к[ \t]+(?:сведениям,?[ \t]+составляющим[ \t]+)?государственн\w*[ \t]+тайн\w*"
    rf"(?:[ \t]+по[ \t]+{_FORM_NUM}[ \t]+форм\w*)?"
    r"|допуск\w*[ \t]+к[ \t]+гостайн\w*"
    r"|(?:действительн\w*[ \t]+)?(?:государственн\w*[ \t]+)?(?:советник|референт|секретар)\w*"
    r"[ \t]+(?:государственн\w*[ \t]+(?:гражданск\w*[ \t]+)?службы[ \t]+)?"
    r"(?:Российской[ \t]+Федерации[ \t]+|субъекта[ \t]+Российской[ \t]+Федерации[ \t]+)?"
    r"(?:[123]|I{1,3})(?:-?го)?[ \t]+класса)(?!\w)",
    re.IGNORECASE)

# Доля в капитале или в праве собственности
_SHARE = (r"\d{1,3}(?:[.,]\d{1,6})?[ \t]*(?:%|процент\w*)(?![\w%])"
          r"|\d{1,4}[ \t]*/[ \t]*\d{1,5}(?![\d/])")
_SHARE_LABEL = (
    r"(?:размер\w*[ \t]+)?дол(?:я|и|ю|ей|ями|е)[ \t]+(?:участия|в[ \t]+(?:уставном[ \t]+|складочном[ \t]+)?"
    r"капитал\w*|в[ \t]+праве(?:[ \t]+общей)?(?:[ \t]+долевой)?(?:[ \t]+собственности)?"
    r"|в[ \t]+(?:ООО|обществе|компании))"
    r"|размер\w*[ \t]+дол\w*|участник\w*[ \t]+с[ \t]+дол\w*"
)
# слова без цифр в пределах строки: "доля ... составляет 25%"
SHARE_RE = re.compile(
    rf"(?<!\w)(?:{_SHARE_LABEL})(?![\w])[^\d\n|]{{0,40}}?({_SHARE})", re.IGNORECASE)
# "владеет 25 % долей", "принадлежит 1/2 доли", "владеет 30% акций"
SHARE_OWN_RE = re.compile(
    rf"(?<!\w)(?:владе\w*|принадлеж\w*)[ \t]+({_SHARE})[ \t]+"
    r"(?:дол\w*|акци\w*|уставного[ \t]+капитала|в[ \t]+уставном[ \t]+капитале)",
    re.IGNORECASE)
