"""Извлечение текста из PDF для маскировки.

Направление одностороннее: PDF на входе, обезличенный ТЕКСТ на выходе. Собрать
PDF обратно нельзя - в нем нет ячеек и абзацев, текст лежит позиционированными
кусками, и замена на метку другой длины ломает верстку строки. Настоящая
редактура PDF (вырезать текст из слоя, закрасить область) - другая задача и
другой инструмент.

Читаем `pdftotext` из poppler: он есть в системе, работает с кириллицей и не
тянет в проект python-зависимость ради одного формата.

**Скан - это отказ, а не пустой результат.** У PDF из сканера нет текстового
слоя, и извлечение возвращает пустоту. Без проверки маскировка отработала бы
"успешно": ноль сущностей, пустой файл на выходе и никакой ошибки - при том что
персональные данные на страницах остались, просто картинкой.
"""
from __future__ import annotations

import shutil
import subprocess
from pathlib import Path

BIN = "pdftotext"


class PdfError(Exception):
    """Понятная человеку причина, по которой из PDF не вышло текста."""


def extract_text(src: str | Path, timeout: int = 120) -> str:
    """Текст PDF с сохранением расположения колонок.

    `-layout` важен для бухгалтерских форм: без него колонки таблицы
    склеиваются в одну строку, и подпись реквизита отрывается от значения.
    """
    if shutil.which(BIN) is None:
        raise PdfError(
            f"нет {BIN} - установи poppler-utils, без него PDF читать нечем")

    proc = subprocess.run([BIN, "-layout", str(src), "-"],
                          capture_output=True, timeout=timeout)
    if proc.returncode != 0:
        detail = proc.stderr.decode("utf-8", "replace").strip().splitlines()
        raise PdfError(f"{BIN} не смог прочитать файл: {detail[-1] if detail else 'без деталей'}")

    text = proc.stdout.decode("utf-8", "replace")
    # Перевод страницы есть даже у пустых страниц - на содержимое он не тянет.
    if not text.replace("\f", "").strip():
        raise PdfError(
            "в PDF нет текстового слоя - похоже, это скан. Обезличивать в нем "
            "нечего: данные лежат картинкой, и текстом их не заменить")
    return text
