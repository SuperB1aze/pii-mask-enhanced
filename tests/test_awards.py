"""Награды и поощрения - только поле анкеты по подписи; остальное - нейросети.

Голое "Достижения:" - содержание резюме, его не трогаем. Данные выдуманные.
"""
import pytest

from masking import mask as _mask


@pytest.mark.parametrize("src, expected", [
    ("Награды: орден Мужества, медаль «За отвагу»", "Награды: {{PERSONAL_1}}"),
    ("Государственные награды: Заслуженный врач РФ", "Государственные награды: {{PERSONAL_1}}"),
    ("Награды и поощрения: Почётная грамота Минздрава", "Награды и поощрения: {{PERSONAL_1}}"),
    ("Награды, достижения: мастер спорта", "Награды, достижения: {{PERSONAL_1}}"),
    ("Достижения и награды: Лучший сотрудник 2023", "Достижения и награды: {{PERSONAL_1}}"),
    ("Поощрения: благодарность руководства", "Поощрения: {{PERSONAL_1}}"),
    ("Почётное звание: Заслуженный учитель РФ", "Почётное звание: {{PERSONAL_1}}"),
    ("Награждения: медаль «За трудовую доблесть»", "Награждения: {{PERSONAL_1}}"),
    ("Награды\nорден Почёта", "Награды\n{{PERSONAL_1}}"),   # подпись на своей строке
])
def test_awards_field_masked(src, expected):
    assert _mask(src) == expected


@pytest.mark.parametrize("src", [
    "Достижения: увеличил продажи на 30%",    # содержание резюме
    "## Достижения",
    "награды вручаются ежегодно",            # без двоеточия - фраза
    "орден Мужества учреждён в 1994 году",   # без подписи - нейросети
])
def test_awards_without_field_untouched(src):
    assert _mask(src) == src
