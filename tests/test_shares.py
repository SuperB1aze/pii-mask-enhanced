"""Доля в капитале или в праве собственности: процент или дробь после явной подписи.

Голое "доля" - и статистика компании ("доля рынка 25%"), его не берем. Данные выдуманные.
"""
import pytest

from pii_mask_enhanced.engine.core import Masker


def _mask(text: str) -> str:
    return Masker(ner=False).mask(text)[0]


@pytest.mark.parametrize("src, expected", [
    ("доля в уставном капитале 25%", "доля в уставном капитале {{PERSONAL_1}}"),
    ("Доля участия: 25 %", "Доля участия: {{PERSONAL_1}}"),
    ("доля в уставном капитале составляет 33,33%",
     "доля в уставном капитале составляет {{PERSONAL_1}}"),
    ("размер доли: 1/4", "размер доли: {{PERSONAL_1}}"),
    ("Иванову И.И. принадлежит доля в праве общей долевой собственности 1/2",
     "{{PERSON_1}} принадлежит доля в праве общей долевой собственности {{PERSONAL_1}}"),
    ("участник с долей 50 процентов", "участник с долей {{PERSONAL_1}}"),
    ("Иванов И.И. владеет 25 % долей", "{{PERSON_1}} владеет {{PERSONAL_1}} долей"),
    ("владеет 30% акций", "владеет {{PERSONAL_1}} акций"),
    ("принадлежит 1/2 доли", "принадлежит {{PERSONAL_1}} доли"),
    ("доля в ООО 100%", "доля в ООО {{PERSONAL_1}}"),
])
def test_share_masked(src, expected):
    assert _mask(src) == expected


@pytest.mark.parametrize("src", [
    "доля рынка 25%",                        # статистика компании
    "доля просроченных кредитов 5%",
    "НДС 20%",
    "доля в уставном капитале оплачена",
    "рост на 25%",
])
def test_share_lookalikes_untouched(src):
    assert _mask(src) == src
