"""Многословная персона: номенклатура товара не должна читаться как ФИО.

Поймано на боевой выгрузке КУДиР: в колонке товаров распознаватель размечал
как людей связки "товар плюс бренд" - "ГИДРОПЛЕКС Тушь", "Крем АКВАЛЮКС".
Однословный фильтр их не видел, потому что слов два.
"""
from pii_mask_enhanced.engine.core import Masker


def _persons(text: str) -> list[str]:
    _, mapping = Masker(types=("PERSON",)).mask(text)
    return [r["key"] for r in mapping["labels"].values() if r["type"] == "PERSON"]


def test_goods_are_not_people():
    for goods in ("ГИДРОПЛЕКС Тушь для ресниц",
                  "Крем АКВАЛЮКС для рук",
                  "Крем-мыло Ромашка"):
        assert _persons(goods) == [], f"товар размечен как человек: {goods}"


def test_real_fio_still_masked():
    """Главное ограничение правила: настоящие ФИО терять нельзя."""
    for fio in ("Ветрова Алевтина Серикбаевна",
                "Орлов Руслан Тахирович",
                "Соколова Анна Владимировна"):
        assert _persons(fio), f"потеряли живого человека: {fio}"


def test_common_noun_surname_survives():
    """Фамилия, совпадающая с обычным словом, остаётся человеком.

    Правило смотрит на весь спан: если хоть один токен несёт граммемы имени,
    спан - человек, даже когда соседний токен словарю знаком как предмет.
    """
    assert _persons("Шапка Иван Петрович")
