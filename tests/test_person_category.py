"""Категория лица: пенсионер, инвалид, многодетный, ветеран, участник СВО...

Рядом с найденным ФИО в той же строке или в поле анкеты. Без человека - текст закона
или новости: "пенсионеры получают надбавку". Данные выдуманные.
"""
import pytest

from masking import mask as _mask


@pytest.mark.parametrize("src, expected", [
    ("Иванов И.И., пенсионер", "{{PERSON_1}}, {{PERSONAL_1}}"),
    ("Иванов И.И., пенсионер по инвалидности", "{{PERSON_1}}, {{PERSONAL_1}}"),
    ("Петрова П.П. (многодетная мать)", "{{PERSON_1}} ({{PERSONAL_1}})"),
    ("Сидоров С.С., инвалид", "{{PERSON_1}}, {{PERSONAL_1}}"),
    ("ветеран боевых действий Петров П.П.", "{{PERSONAL_1}} {{PERSON_1}}"),
    ("Иванов И.И., участник СВО", "{{PERSON_1}}, {{PERSONAL_1}}"),
    ("Иванова А.А., мать-одиночка", "{{PERSON_1}}, {{PERSONAL_1}}"),
    ("Смирнов С.С., VIP-клиент", "{{PERSON_1}}, {{PERSONAL_1}}"),
    ("Иванов И.И., ликвидатор аварии на ЧАЭС", "{{PERSON_1}}, {{PERSONAL_1}}"),
    # поле анкеты
    ("Льготная категория: ветеран труда", "Льготная категория: {{PERSONAL_1}}"),
    ("Социальный статус: пенсионер", "Социальный статус: {{PERSONAL_1}}"),
    ("Категория гражданина: многодетная семья", "Категория гражданина: {{PERSONAL_1}}"),
    ("Льготы: инвалид II группы", "Льготы: {{PERSONAL_1}}"),
    ("Статус клиента: VIP", "Статус клиента: {{PERSONAL_1}}"),
])
def test_person_category_masked(src, expected):
    assert _mask(src) == expected


@pytest.mark.parametrize("src", [
    "пенсионеры получают надбавку",          # без человека рядом
    "ветераны труда имеют право",
    "Категория: Электроника",                # голое "Категория:" - и категория товара
    "категория товара: бытовая техника",
    "Иванов И.И.\nпенсионер",                # следующая строка - уже про другое
])
def test_category_without_person_untouched(src):
    assert "{{PERSONAL" not in _mask(src)
