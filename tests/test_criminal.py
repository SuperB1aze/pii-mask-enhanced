"""Судимость и преследование - специальная категория ПД (ст. 10 152-ФЗ).

Статья кодекса - ПД только при слове о преследовании рядом: "осужден по ст. 159 УК РФ".
Сама по себе статья - текст закона, договора или комментария. Данные выдуманные.
"""
import pytest

from masking import mask as _mask


@pytest.mark.parametrize("src, expected", [
    ("осуждён по ч. 2 ст. 159 УК РФ", "осуждён по {{PERSONAL_1}}"),
    ("Иванов И.И. осужден 12.03.2015 по п. «а» ч. 2 ст. 158 УК РФ к 2 годам",
     "{{PERSON_1}} осужден 12.03.2015 по {{PERSONAL_1}} к 2 годам"),
    ("обвиняется в совершении преступления, предусмотренного ст. 105 УК РФ",
     "обвиняется в совершении преступления, предусмотренного {{PERSONAL_1}}"),
    ("привлечён к административной ответственности по ч. 1 ст. 12.8 КоАП РФ",
     "привлечён к административной ответственности по {{PERSONAL_1}}"),
    ("судим по ст. 228 УК РФ", "судим по {{PERSONAL_1}}"),
    ("возбуждено уголовное дело по ст. 159, 160 УК РФ", "возбуждено уголовное дело по {{PERSONAL_1}}"),
    ("подозреваемый по статье 158 Уголовного кодекса РФ", "подозреваемый по {{PERSONAL_1}}"),
    # обороты о судимости
    ("ранее судим", "{{PERSONAL_1}}"),
    ("ранее не судима", "{{PERSONAL_1}}"),
    ("имеет непогашенную судимость", "{{PERSONAL_1}}"),
    ("судимость погашена", "{{PERSONAL_1}}"),
    ("не привлекался к уголовной ответственности", "{{PERSONAL_1}}"),
    # поле анкеты: и отсутствие судимости - сведения о человеке
    ("Судимость: не имеется", "Судимость: {{PERSONAL_1}}"),
    ("Сведения о судимости: имеется, ст. 158 УК РФ", "Сведения о судимости: {{PERSONAL_1}}"),
])
def test_criminal_record_masked(src, expected):
    assert _mask(src) == expected


@pytest.mark.parametrize("src", [
    "ст. 159 УК РФ предусматривает наказание до 10 лет",
    "согласно ч. 1 ст. 12.8 КоАП РФ штраф составляет",
    "Статья 158 УК РФ. Кража",
    "понятие судимости в ст. 86 УК РФ",
    "в соответствии со ст. 81 ТК РФ",            # трудовой кодекс - не преследование
])
def test_law_text_untouched(src):
    assert _mask(src) == src
