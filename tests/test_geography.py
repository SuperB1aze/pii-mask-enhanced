"""География: страна, город, регион, адрес без "ул.", индекс, код города, координаты.

Название места без подписи или слова-признака ("г.", "область") не маскируется:
"Банк России", "Москва - столица" - не персданные. Данные в тестах выдуманные.
"""
import pytest

from masking import mask as _mask


@pytest.mark.parametrize("src, expected", [
    # страна и регион по подписи
    ("страна: Казахстан", "страна: {{ADDRESS_1}}"),
    ("Страна проживания: Республика Беларусь", "Страна проживания: {{ADDRESS_1}}"),
    ("регион: Тверская область", "регион: {{ADDRESS_1}}"),
    ("Населённый пункт: Тверь", "Населённый пункт: {{ADDRESS_1}}"),
    ("место рождения: г. Тверь", "место рождения: {{ADDRESS_1}}"),
    # город по слову перед ним
    ("уроженец г. Тверь", "уроженец г. {{ADDRESS_1}}"),
    ("в городе Ростов-на-Дону", "в городе {{ADDRESS_1}}"),
    ("пгт Селятино", "пгт {{ADDRESS_1}}"),
    # регион сам по себе
    ("Тверская область", "{{ADDRESS_1}}"),
    ("Пермский край", "{{ADDRESS_1}}"),
    ("Кировский р-н", "{{ADDRESS_1}}"),
    ("Республика Татарстан", "{{ADDRESS_1}}"),
    ("Ханты-Мансийский автономный округ", "{{ADDRESS_1}}"),
    # улица без "ул." и дом без "д."
    ("Ленина, 5, кв. 12", "{{ADDRESS_1}}"),
    ("г. Тверь, Ленина 5-12", "{{ADDRESS_1}}"),
    ("Адрес: Тверь, Ленина 5-12", "Адрес: {{ADDRESS_1}}"),
    ("адрес регистрации: Тверь, Ленина 5", "адрес регистрации: {{ADDRESS_1}}"),
    ("зарегистрирован по адресу Тверь, Ленина 5", "зарегистрирован по адресу {{ADDRESS_1}}"),
    # индекс
    ("индекс: 125009", "индекс: {{ADDRESS_1}}"),
    ("почтовый индекс 125009", "почтовый индекс {{ADDRESS_1}}"),
    # код города без номера
    ("код города 495", "код города {{ADDRESS_1}}"),
    ("код города: (495)", "код города: {{ADDRESS_1}}"),
    ("тел. (495)", "тел. {{ADDRESS_1}}"),
    # координаты
    ("координаты 55.7558, 37.6173", "координаты {{ADDRESS_1}}"),
    ("55.7558, 37.6173", "{{ADDRESS_1}}"),
    ("GPS: 55.75, 37.61", "GPS: {{ADDRESS_1}}"),
    ("широта: 55.7558", "широта: {{ADDRESS_1}}"),
    ("55°45′N 37°37′E", "{{ADDRESS_1}} {{ADDRESS_2}}"),
    ("55°45′20″ с.ш.", "{{ADDRESS_1}}"),
])
def test_geography_masked(src, expected):
    assert _mask(src) == expected


@pytest.mark.parametrize("src", [
    "страна происхождения: Китай",          # про товар
    "в 2020 г. Москва приняла закон",        # "г." после числа - год
    "см. с. 15",
    "Предметная область",                    # не на -ск-: не регион
    "Глава 5, пункт 3",                      # без квартиры и населенного пункта - не адрес
    "IP-адрес: сервер",
    "Индекс 300026",                         # без двоеточия - число (tests/test_address_run)
    "цены 12.50, 13.75",                     # без подписи координатам нужно 4+ знака
    "температура 25°C",
    "угол 30°",
    "ИФНС по г. Твери",                      # территория ведомства
])
def test_geography_lookalikes_untouched(src):
    assert _mask(src) == src


def test_citizenship_stays_personal():
    """Страна гражданства - сведения о человеке, а не адрес."""
    assert _mask("гражданство: Республика Беларусь") == "гражданство: {{PERSONAL_1}}"


def test_phone_with_city_code_stays_phone():
    assert _mask("тел. (495) 123-45-67") == "тел. +7 000 000-00-01"


def test_city_inside_address_found_once():
    from pii_mask_enhanced.detection.recognizers.recognizers import find_format_entities

    ents = [e for e in find_format_entities("125009, г. Москва, Тверская ул., д. 1")
            if e.type == "ADDRESS"]
    assert len(ents) == 1
