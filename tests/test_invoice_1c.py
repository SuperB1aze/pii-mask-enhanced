"""Счет на оплату из 1С: три утечки, найденные на живом документе 02.09.2026.

Данные в фикстуре выдуманы - репозиторий публичный. Номера счетов и ИНН
синтетические: контрольные суммы валидны (иначе распознаватель их не берет),
но сами номера не принадлежат никому. Воспроизводится форма
документа, а не чьи-то реквизиты: бланк счета 1С с колоночной версткой,
переносами строк внутри адреса и подписью в подвале.
"""
import pytest

from pii_mask_enhanced.engine.core import Masker

# Бланк счета: колонки разделены широкой отбивкой, адрес разорван переводом
# строки, а дата основания уехала на следующую строку внутри табличной ячейки.
СЧЕТ = """\
Счет на оплату № 260 от 02 сентября 2026 г.

Поставщик      Индивидуальный предприниматель Черных Ольга Петровна
(Исполнитель): ИНН 500100732001, 140000, Московская обл,
               г. Кубинка, ул. Полевая, д. 12, кв. 3

Покупатель        ООО "Ромашка", ИНН 5001007329,
(Заказчик):       г.о. Одинцовский, г. Одинцово, ул. Садовая, д. 1, кв. 11

Основание:        260 от 01.09.2026

 №     Товары (работы, услуги)                            Цена         Сумма
 1     Оказание услуг согласно договора № 260 от          400 000,00   400 000,00
       01.09.2026г.

Предприниматель                                           Черных О. П.
"""


@pytest.fixture(scope="module")
def маска():
    m = Masker(types=("PERSON", "ORG", "INN", "ADDRESS", "DOCREF", "DATE", "PHONE"),
               ner_org_needs_form=True, ner_person_needs_fio=True,
               inn_needs_label=True)
    return m.mask(СЧЕТ)[0]


def test_фамилия_не_остается_рядом_с_замаскированным_именем(маска):
    """Несклоняемая фамилия на -их выпадала из спана ФИО.

    Живой случай: в строке поставщика распознаватель закрыл имя и отчество, а
    фамилию оставил открытой - при том что в подвале та же фамилия с инициалами
    была замаскирована целиком. Документ выглядел обезличенным, а ИП назван.
    """
    assert "Черных" not in маска


def test_дата_основания_закрывается_вместе_с_номером(маска):
    """Номер договора без даты не идентифицирует сделку, вместе с датой - да.

    "Основание: 260 от 01.09.2026": номер закрывался повтором от другого
    вхождения, а дата рядом с ним оставалась открытой.
    """
    assert "01.09.2026" not in маска


def test_городской_округ_попадает_в_адрес(маска):
    """"г.о." не было в словаре адресных указателей.

    Соседние куски того же адреса закрывались, а округ оставался - поле
    выглядело обезличенным, хотя география в нем сохранилась.
    """
    assert "Одинцовский" not in маска


def test_не_испортили_остальное(маска):
    """Суммы и наименование услуги - не ПД, их трогать нельзя."""
    assert "400 000,00" in маска
    assert "Оказание услуг" in маска


# --- банковский блок ---

БАНК = """\
Банк получателя   ПАО БАНК "ПРИМЕР" г. Кубинка
БИК                                    049999999
                                       Сч. № 30101810000000000002
ИНН 500100732001   КПП 500101001       Сч. № 40802810000000000001
"""


def test_счета_и_бик_закрываются(маска_банка):
    """Расчетный счет опознает предпринимателя не хуже ИНН.

    Раньше оставались открытыми оба: БИК падал в общий тип REQ, который в
    бухгалтерских документах держат выключенным (под него уходят номера
    первички), а двадцатизначный счет не подходил под потолок в 15 знаков.
    """
    assert "049999999" not in маска_банка
    assert "30101810000000000002" not in маска_банка
    assert "40802810000000000001" not in маска_банка


def test_подписи_реквизитов_остаются_на_месте(маска_банка):
    """Затираем значения, а не подписи - иначе бланк перестает читаться."""
    for подпись in ("БИК", "Сч. №", "ИНН", "КПП"):
        assert подпись in маска_банка


@pytest.fixture(scope="module")
def маска_банка():
    m = Masker(types=("PERSON", "ORG", "INN", "KPP", "BIK", "ACCOUNT", "ADDRESS"),
               ner_org_needs_form=True, ner_person_needs_fio=True,
               inn_needs_label=True)
    return m.mask(БАНК)[0]
