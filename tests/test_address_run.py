"""Адрес в бланке: индекс открывает его, граница колонки закрывает.

Поймано на счете-фактуре: адрес ИП "300026, Тульская область, Zarechny,
Солнечный тер. СНТ,, 12" маскировался только индексом, остальное оставалось
открытым. Расширять шаблон под каждую форму записи ("область" вместо "обл",
город латиницей, "тер." вместо "ул.", дом без "д.") - гонка без конца, а
признак "после индекса идет адрес" держится на любой из них.
"""
from pii_mask_enhanced.engine.core import Masker


def _mask(text: str) -> str:
    return Masker(types=("ADDRESS",)).mask(text)[0]


def test_index_pulls_the_whole_address():
    src = "Адрес     300026, Тульская область, Zarechny, Солнечный тер. СНТ,, 12"
    out = _mask(src)
    for part in ("300026", "Тульская", "Zarechny", "Солнечный"):
        assert part not in out, f"часть адреса осталась открытой: {part}"


def test_column_break_stops_the_address():
    """Широкая отбивка - граница колонки бланка, а не продолжение адреса."""
    src = "300026, Тульская область, Zarechny          Валюта: RUB, 643"
    out = _mask(src)
    assert "Валюта: RUB, 643" in out
    assert "Тульская" not in out


def test_newline_stops_the_address():
    out = _mask("125009, г. Москва, Тверская ул., д. 7\nИНН 6083778353")
    assert "ИНН 6083778353" in out
    assert "Тверская" not in out


def test_bare_index_alone_is_not_an_address():
    """Шестизначное число без адреса за ним - не адрес, и не было им раньше.

    Индекс опознается только по тому, что за ним идет адрес: одинокие шесть
    цифр это с равным успехом артикул, код или сумма.
    """
    assert "300026" in _mask("Индекс 300026")
