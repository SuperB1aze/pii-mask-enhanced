"""Повтор номера в другой записи: пробелы, дефисы и "№" между знаками не мешают найти
тот же номер второй раз - и он получает ту же метку.

Гибко ищется только номер: от 6 цифр и без других знаков. Короткий номер ("12/24")
и логин ("ivanov_i") - точной копией. Данные выдуманные.
"""
import pytest

from masking import mask as _mask


@pytest.mark.parametrize("src, expected", [
    ("серия 77 № 007893219, позже 77 007893219 и 77№007893219",
     "серия {{GOVDOC_1}}, позже {{GOVDOC_1}} и {{GOVDOC_1}}"),
    ("СНИЛС 112-233-445 95, в анкете 11223344595 и 112 233 445 95",
     "СНИЛС {{SNILS_1}}, в анкете {{SNILS_1}} и {{SNILS_1}}"),
    ("ВУ 77 АА 123456, ниже 77АА123456", "ВУ {{IDDOC_1}}, ниже {{IDDOC_1}}"),
    ("ИНН 7701234567, повтор 770 123 4567", "ИНН {{INN_1}}, повтор {{INN_1}}"),
    # паспорт тоже распространяется: номер у слова "паспорт" скрыт и без него
    ("паспорт 4510 123456, ниже 4510123456", "паспорт {{PASSPORT_1}}, ниже {{PASSPORT_1}}"),
    ("Иванов И.И. паспорт 4510 123456\nКлиент 4510-123456 обратился",
     "{{PERSON_1}} паспорт {{PASSPORT_1}}\nКлиент {{PASSPORT_1}} обратился"),
])
def test_repeat_in_other_spelling(src, expected):
    assert _mask(src) == expected


@pytest.mark.parametrize("src, expected", [
    # короткий номер - только точной копией: "12 24 шт." - не договор
    ("Договор № 12/24, далее 12 24 шт.", "Договор № {{REQ_1}}, далее 12 24 шт."),
    # номер внутри более длинного числа - не повтор
    ("СНИЛС 112-233-445 95, счёт 1122334459512", "СНИЛС {{SNILS_1}}, счёт 1122334459512"),
    # логин - точной копией, подчеркивание - часть значения
    ("логин: ivanov_i. Вход под ivanov_i", "логин: {{PERSON_ID_1}}. Вход под {{PERSON_ID_1}}"),
])
def test_repeat_limits(src, expected):
    assert _mask(src) == expected
