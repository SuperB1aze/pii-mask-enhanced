"""Здоровье - специальная категория ПД (ст. 10 152-ФЗ): диагноз, код МКБ-10, инвалидность.

Код МКБ без подписи неотличим от артикула, поэтому берется только после "диагноз",
"Ds", "код МКБ". Данные выдуманные.
"""
import pytest

from masking import mask as _mask


@pytest.mark.parametrize("src, expected", [
    # код МКБ-10
    ("диагноз J45.0", "диагноз {{PERSONAL_1}}"),
    ("Ds: I10", "Ds: {{PERSONAL_1}}"),
    ("д-з Е11.9", "д-з {{PERSONAL_1}}"),                     # буква кода кириллицей
    ("код по МКБ-10: J45.0, I10", "код по МКБ-10: {{PERSONAL_1}}"),
    ("МКБ-10 F32.1", "МКБ-10 {{PERSONAL_1}}"),
    # поле анкеты или выписки - до конца строки
    ("Диагноз: J45.0 Бронхиальная астма, средней тяжести", "Диагноз: {{PERSONAL_1}}"),
    ("Основной диагноз: гипертоническая болезнь II стадии", "Основной диагноз: {{PERSONAL_1}}"),
    ("заболевание: сахарный диабет 2 типа", "заболевание: {{PERSONAL_1}}"),
    ("Состояние здоровья: удовлетворительное", "Состояние здоровья: {{PERSONAL_1}}"),
    ("Противопоказания: нет", "Противопоказания: {{PERSONAL_1}}"),
    ("Аллергия: пенициллин", "Аллергия: {{PERSONAL_1}}"),
    ("аллергия на пенициллин", "аллергия на {{PERSONAL_1}}"),
    ("группа здоровья: II", "группа здоровья: {{PERSONAL_1}}"),
    # инвалидность
    ("инвалид II группы", "{{PERSONAL_1}}"),
    ("II группы инвалидности", "{{PERSONAL_1}}"),
    ("группа инвалидности: 2", "{{PERSONAL_1}}"),
    ("ребёнок-инвалид", "{{PERSONAL_1}}"),
    ("инвалид детства", "{{PERSONAL_1}}"),
    ("ограничение трудоспособности", "{{PERSONAL_1}}"),
    ("Инвалидность: II группа, бессрочно", "Инвалидность: {{PERSONAL_1}}"),
])
def test_health_masked(src, expected):
    assert _mask(src) == expected


@pytest.mark.parametrize("src", [
    "артикул J45.0",                                 # код без подписи
    "МКБ-10 - международная классификация болезней",
    "заболевание гриппом распространено",            # без двоеточия - фраза
    "диагноз ставит врач",
    "группа инвалидов прибыла",
    "I группа товаров",
])
def test_health_lookalikes_untouched(src):
    assert _mask(src) == src
