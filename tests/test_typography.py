"""Типографские близнецы дефиса и пробела ломают распознавание.

Прецедент 28.09.2026: резюме в PDF, собранное нашим же генератором, содержало
21 неразрывный дефис U+2011. Для токенизатора название
работодателя через такой дефис - не слово, поэтому ни организация, ни
стоящая рядом фамилия не были найдены вовсе: документ
выглядел обезличенным, а человек и его работодатель в нем названы.

Отсюда два требования, и второе не менее важно первого: искать по
нормализованному тексту, а отдавать символы клиента как были.
"""
from pii_mask_enhanced.engine.core import Masker


def test_non_breaking_hyphen_does_not_split_a_name():
    """Неразрывный дефис внутри слова - и половина фамилии остается открытой.

    Без нормализации распознаватель видит в "Корнеева\u2011Ким" два куска и
    забирает только второй: документ выглядит обезличенным, а человек в нем
    наполовину назван. На живом резюме тем же дефисом были потеряны и фамилия,
    и работодатель целиком.
    """
    masked, _ = Masker(types=("PERSON",)).mask(
        "Корнеева\u2011Ким Алина Рустамовна, руководитель")
    assert "Корнеева" not in masked, masked
    assert "Ким" not in masked, masked


def test_client_characters_come_back_untouched():
    """Нормализация - для поиска, а не для документа.

    Маскер зовут и на ячейке Excel, и на абзаце Word: подменив там неразрывный
    дефис обычным, мы правили бы чужой документ по дороге.
    """
    text = "Дата‑центр и ИТ‑проекты, 200 млн рублей"
    masked, mapping = Masker(types=("PERSON", "ORG"), ner=False).mask(text)
    assert masked == text
    assert mapping["labels"] == {}


def test_offsets_do_not_shift_after_normalization():
    """Замены 1:1 по длине - иначе маска встанет не на то место."""
    text = "Контакты: user@example.ru, ИТ‑отдел, +7 916 000-00-02"
    masked, _ = Masker(types=("EMAIL", "PHONE"), ner=False).mask(text)
    assert "user@example.ru" not in masked
    assert "ИТ‑отдел" in masked, masked


def test_surname_next_to_patronymic_is_masked():
    """Отчество - жесткий якорь: соседнее слово при нем это фамилия.

    NER регулярно отдает только "Имя Отчество", а фамилию оставляет снаружи -
    и документ выглядит обезличенным при названном человеке. Прецедент тот же,
    резюме от 28.09.2026: в шапке осталась фамилия.
    """
    masked, _ = Masker(types=("PERSON",)).mask("Сухарева Алина Рустамовна, Москва")
    assert "Сухарева" not in masked, masked
    assert "Москва" in masked, "город не ФИО - его трогать нечем"


def test_surname_after_the_name_is_masked_too():
    masked, _ = Masker(types=("PERSON",)).mask("Исполнитель: Алина Рустамовна Сухарева")
    assert "Сухарева" not in masked, masked


def test_position_before_the_name_survives():
    """Слово рядом с ФИО принимается только если словарь знает его как имя."""
    masked, _ = Masker(types=("PERSON",)).mask("Руководитель Алина Рустамовна ушла")
    assert "Руководитель" in masked, masked


def test_org_in_oblique_case_is_masked_everywhere():
    """Название, признанное организацией, закрывается и в косвенном падеже.

    В резюме работодатель назван дважды: строкой опыта и фразой в саммари
    ("11 лет в Светописи"). Буквальный повтор вторую не видит - окончание
    другое, - и место работы остается названным при живой маске рядом.
    Источник подтверждения здесь словарь: так тест не зависит от того, какие
    названия знает языковая модель.
    """
    text = ("Светопись, 02.2014 - 01.2025\n"
            "Руководитель отдела\n"
            "24 года в отрасли, из них 11 лет в Светописи - от аналитика")
    masked, mapping = Masker(types=("ORG",), org_names=("Светопись",)).mask(text)
    assert "Светописи" not in masked, masked
    assert len(mapping["labels"]) == 1, "это одна организация, а не две"


def test_object_name_in_quotes_after_generic_word():
    """Родовое слово плюс кавычки - это название, даже без правовой формы.

    В досье по опыту объекты названы так: ТРЦ "Ромашка", БЦ "Полевой". Правовой
    формы рядом нет, NER такие названия не берет, и место работы остается в
    тексте открытым. Само родовое слово не имя - его оставляем, иначе из
    документа уходит масштаб объекта.
    """
    text = 'Масштаб: группа объектов - ТРЦ "Ромашка" 330 тыс. м², БЦ "Полевой" класса А'
    masked, mapping = Masker(types=("ORG",), ner=False).mask(text)
    assert "Ромашка" not in masked, masked
    assert "Полевой" not in masked, masked
    assert "ТРЦ" in masked and "БЦ" in masked, "тип объекта - не имя"
    assert len(mapping["labels"]) == 2


def test_org_declension_changes_the_ending():
    """Косвенный падеж меняет окончание, а не прирастает к названию.

    "Ромашка" в предложном - "Ромашке": буквальный повтор такое не
    находит, и работодатель, замаскированный в шапке, остается назван в тексте.
    """
    text = ('ООО "Ромашка" - основное место работы.\n'
            'Даты в Ромашке - по фактической работе, как решили 22.09.')
    masked, mapping = Masker(types=("ORG",), ner=False).mask(text)
    assert "Ромашке" not in masked, masked
    assert len(mapping["labels"]) == 1, "это одна организация, а не две"
