"""Доход и удержания человека: оклад, зарплата, премия, пенсия, алименты, "удержано".

Сумма сама по себе - не ПД: в счетах и выгрузках 1С она должна остаться. Поэтому
только однозначно личные подписи; "доход", "НДФЛ" без уточнения - и статьи отчетности
компании, их оставляем нейросети. Данные в тестах выдуманные.
"""
import pytest

from pii_mask_enhanced.engine.core import Masker
from pii_mask_enhanced.formats.office_xml import cell_label_type


def _mask(text: str) -> str:
    return Masker(ner=False).mask(text)[0]


@pytest.mark.parametrize("src, expected", [
    ("оклад 120 000 руб.", "оклад {{INCOME_1}}"),
    ("Должностной оклад: 120000", "Должностной оклад: {{INCOME_1}}"),
    # сумма прописью закрывается вместе с цифрами
    ("оклад в размере 120 000 (сто двадцать тысяч) рублей 00 копеек в месяц",
     "оклад в размере {{INCOME_1}} в месяц"),
    ("заработная плата составляет 85 000,50 руб.", "заработная плата составляет {{INCOME_1}}"),
    ("ЗП 150к", "ЗП {{INCOME_1}}"),
    ("з/п 90 тыс. руб.", "з/п {{INCOME_1}}"),
    ("желаемая зарплата: от 150 000 до 200 000 ₽", "желаемая зарплата: от {{INCOME_1}}"),
    ("Зарплатные ожидания: 150–200 тыс.", "Зарплатные ожидания: {{INCOME_1}}"),
    ("премия 25 000 руб.", "премия {{INCOME_1}}"),
    ("алименты за 2024 год составили 240 000 руб.",
     "алименты за 2024 год составили {{INCOME_1}}"),
    ("пенсия 23 500 р.", "пенсия {{INCOME_1}}"),
    ("пособие по уходу за ребенком 1 500 руб.", "пособие по уходу за ребенком {{INCOME_1}}"),
    ("К выплате: 104 400,00", "К выплате: {{INCOME_1}}"),
    ("на руки 104 400", "на руки {{INCOME_1}}"),
    ("Удержано НДФЛ 15 600,00", "Удержано НДФЛ {{INCOME_1}}"),
    ("НДФЛ удержан в сумме 15 600 руб.", "НДФЛ удержан в сумме {{INCOME_1}}"),
    ("удержание по исполнительному листу с 01.03.2024 10 000 руб.",
     "удержание по исполнительному листу с 01.03.2024 {{INCOME_1}}"),
    ("среднемесячный доход 180 000", "среднемесячный доход {{INCOME_1}}"),
    ("ежемесячный платеж по кредиту 25 000 руб.", "ежемесячный платеж по кредиту {{INCOME_1}}"),
])
def test_income_masked(src, expected):
    assert _mask(src) == expected


@pytest.mark.parametrize("src", [
    "оклад 5 разряда",                       # короткое число без валюты - не сумма
    "премия 2 раза в год",
    "премия в размере 15% оклада",           # доля, а не сумма
    "премия 15-20%",
    "пенсия по старости назначена с 2020 г.",  # год - не сумма
    "итого по счету 1 200 000 руб.",         # сумма компании
    "доходы будущих периодов 1 200 000",     # статья отчетности
    "аванс 30% по договору 500 000 руб.",    # платеж по договору
    "НДФЛ 13%",
])
def test_not_an_income(src):
    assert _mask(src) == src


def test_income_in_table_cell():
    assert cell_label_type("Оклад", "120 000,00") == "INCOME"
