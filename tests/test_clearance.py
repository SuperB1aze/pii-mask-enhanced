"""Допуск к гостайне и классный чин гражданской службы.

Обороты однозначные - человек рядом не нужен. "Допуск к работе", "допуск к торгам" -
не про гостайну. Данные выдуманные.
"""
import pytest

from masking import mask as _mask


@pytest.mark.parametrize("src, expected", [
    ("форма допуска № 2", "{{PERSONAL_1}}"),
    ("форма допуска: 2", "{{PERSONAL_1}}"),
    ("оформлена форма допуска 1", "оформлена {{PERSONAL_1}}"),
    ("имеет допуск по 2 форме", "имеет {{PERSONAL_1}}"),
    ("допуск по второй форме", "{{PERSONAL_1}}"),
    ("допуск к сведениям, составляющим государственную тайну", "{{PERSONAL_1}}"),
    ("допуск к государственной тайне по 3 форме", "{{PERSONAL_1}}"),
    ("допуск к гостайне", "{{PERSONAL_1}}"),
    # классный чин
    ("советник государственной гражданской службы Российской Федерации 1 класса", "{{PERSONAL_1}}"),
    ("действительный государственный советник 2 класса", "{{PERSONAL_1}}"),
    ("референт государственной гражданской службы 3 класса", "{{PERSONAL_1}}"),
    # поле анкеты: подпись остается, значение закрывается
    ("Классный чин: советник 1 класса", "Классный чин: {{PERSONAL_1}}"),
    ("Допуск к гостайне: имеется", "Допуск к гостайне: {{PERSONAL_1}}"),
    ("Допуск: 2 форма", "Допуск: {{PERSONAL_1}}"),
])
def test_clearance_masked(src, expected):
    assert _mask(src) == expected


@pytest.mark.parametrize("src", [
    "допуск к работе",
    "допуск к торгам",
    "форма заявки № 2",
    "допуск транспортного средства",
    "советник директора",
])
def test_not_a_clearance(src):
    assert _mask(src) == src
