"""Профиль документа: резюме против бухгалтерской выгрузки.

Требование правовой формы у организации (ner_org_needs_form) введено для
выгрузок 1С: без него NER метит организациями торговые марки и кромсает колонку
товаров. На резюме то же требование работает наоборот - работодатели там пишутся
без ООО и без кавычек, и режим оставляет открытыми почти все места работы
(замер 28.09.2026 на живом резюме: 3 организации против 62).

Отсюда профиль по документу, а не один режим на все.
"""
from pii_mask_enhanced.detection.profile import looks_like_resume

РЕЗЮМЕ = """Иванов Иван
Руководитель проектного офиса
Ключевые компетенции: управление портфелем проектов, бюджет, риски
Опыт работы
2014 - 2025, руководитель отдела развития
Образование: МФТИ
"""

ВЫГРУЗКА = """Книга учета доходов и расходов
№ п/п | Дата и номер первичного документа | Содержание операции | Доходы
1 | Платежное поручение № 41 от 03.02.2026 | Оплата по договору | 120 000,00
ИТОГО за I квартал
"""


def test_resume_is_recognized():
    assert looks_like_resume(РЕЗЮМЕ)


def test_ledger_is_not_a_resume():
    assert not looks_like_resume(ВЫГРУЗКА)


def test_one_marker_is_not_enough():
    """Слово "образование" встречается и в уставе, и в договоре."""
    assert not looks_like_resume("Договор оказания услуг в сфере образования. ИНН 7701234567")


def test_empty_text_is_not_a_resume():
    assert not looks_like_resume("")


КРАТКОЕ_CV = """Петрова Мария
Руководитель проектного офиса
Москва | +7 916 000-00-02 | telegram: @petrova
Ключевые компетенции: управление портфелем, бюджет, риски

Ромашка, 02.2014 - 01.2025
Руководитель отдела, 01.2021 - 01.2025
Ранее: аналитик (02.2014 - 10.2017)
"""

СЧЕТ = """Счет на оплату № 41 от 03.02.2026
Поставщик: ООО "Ромашка", ИНН 7701234567, КПП 770101001
Должность: главный бухгалтер
Образование заказчика значения не имеет
Срок действия договора 2024 - 2026, продление 2026 - 2028
"""


def test_short_cv_is_recognized_by_periods():
    """Словесных маркеров тут два - узнать резюме можно только по периодам."""
    assert looks_like_resume(КРАТКОЕ_CV)


def test_invoice_with_periods_is_still_paper():
    """КПП и ИНН перевешивают: резюме с расчетными реквизитами не бывает."""
    assert not looks_like_resume(СЧЕТ)


МИНИМАЛЬНОЕ_CV = """Мария Петрова
Product Analyst | Продуктовый аналитик | SQL Python
+7 916 000-00-02   tg: @petrova   petrova@example.ru

О себе
Аналитик данных с 1,5 годами коммерческого опыта в BI и DWH.

Стек: SQL, Python, Airflow
Проекты
Образование
2022 – 2026 Университет
"""


def test_cv_with_dash_periods_and_contact_line():
    """Резюме без слов "опыт работы": периоды через тире и строка контактов.

    Промах 28.09.2026: такое резюме определилось деловым документом, включился
    строгий режим - и имя кандидата осталось в тексте открытым.
    """
    assert looks_like_resume(МИНИМАЛЬНОЕ_CV)


def test_letter_with_a_phone_is_not_a_resume():
    """Одна контактная строка резюме не делает."""
    письмо = ("Добрый день! Направляю коммерческое предложение по договору.\n"
              "С уважением, отдел продаж, +7 916 000-00-02, sales@example.ru")
    assert not looks_like_resume(письмо)
