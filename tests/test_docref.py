"""Ссылка на документ: "Договор № X от ДД.ММ.ГГГГ".

Поймано на акте и отчете агента маркетплейса: номер договора, номер доверенности
и их даты оставались в обезличенном документе. По ним сделка опознается целиком,
поэтому владелец документа просила убирать и их.

Тип узкий и якорится на слово ("договор", "доверенность", "контракт"), а не на
любое "№": общий реквизит ловит и номер первичного документа в КУДиР, а его
маскировать нельзя - без него книга не сверяется с первичкой.

Номера в тестах выдуманные: репозиторий публичный.
"""
from pii_mask.core import Masker


def _mask(text: str) -> str:
    return Masker(types=("DOCREF", "DATE"), ner=False).mask(text)[0]


def test_contract_with_letter_prefix():
    out = _mask("Договор МП АБ-11111/24 от 25.01.2023")
    assert "АБ-11111/24" not in out and "25.01.2023" not in out
    assert "Договор" in out


def test_power_of_attorney_short_date():
    out = _mask("действующей на основании Доверенности № 63 от 02.12.24, состав")
    assert "63" not in out and "02.12.24" not in out
    assert "Доверенности" in out


def test_offer_statement():
    out = _mask("в рамках заявления-оферты № 7777777/23 от 26.02.2023 (Договор)")
    assert "7777777/23" not in out and "26.02.2023" not in out


def test_anchor_without_number_untouched():
    """Слово "договор" само по себе - обычный текст, а не ссылка."""
    src = "по договорам купли-продажи Товаров, заключаемых между Заказчиком"
    assert _mask(src) == src


def test_distant_number_not_swallowed():
    """В верстке за словом идет колонка с суммой - это не номер договора."""
    src = "штраф за нарушение условий Договора                        0"
    assert _mask(src) == src


def test_primary_document_number_untouched():
    """Номер первички в КУДиР к ссылкам на договор не относится."""
    src = "05.01.2025, № 4"
    assert _mask(src) == src


def test_date_alone_is_not_masked():
    """Даты вообще не трогаем - в бухгалтерском документе они несут экономику.

    Маскируется только та дата, что стоит внутри ссылки на документ.
    """
    src = "Период с 01.01.2025 по 31.03.2025, оплата 15.02.2025"
    assert _mask(src) == src


def test_number_is_taken_whole():
    """Маска встает с начала номера, а не с его середины.

    Прослойка между словом и номером умеет съесть первые буквы самого номера
    ("Договор МП И" + "Р-11111/24"), и тогда в документе остается огрызок,
    по которому договор все еще узнается.
    """
    out = _mask("Договор МП ИР-11111/24 от 25.01.2023")
    assert "ИР-11111/24" not in out
    assert "И{{" not in out and "ИР{{" not in out


def test_date_gets_its_own_label():
    """Номер и дата - разные сущности, и метки у них разные.

    Под одной меткой они читаются хуже, а в реестре неразличимы: непонятно,
    что разворачивать в номер, а что в дату.
    """
    out = _mask("Договор АБ-11111/24 от 25.01.2023")
    assert "{{DOCREF_1}}" in out and "{{DATE_1}}" in out


def test_date_type_does_not_mask_dates_at_large():
    """Тип DATE включает ТОЛЬКО дату внутри ссылки на документ.

    Маскировать все даты подряд нельзя: в бухгалтерском документе они несут
    экономику - период, дата оплаты, дата отгрузки. Тест фиксирует границу,
    чтобы смысл типа не расползся при следующей правке.
    """
    src = "Период с 01.01.2025 по 31.03.2025, оплата 15.02.2025, отгрузка 20.02.2025"
    assert _mask(src) == src


def test_invoice_and_waybill_are_documents():
    """Счет-фактура, накладная, УПД - такие же ссылки на документ.

    Найдено на акте маркетплейса: "Счет-фактура № 74255758 от ..." оставался
    открытым, потому что этого слова не было среди якорей.
    """
    for src in ("Счет-фактура № 11111111 от 31.07.2026",
                "Накладная № АБ-222 от 01.02.25",
                "УПД № 333/24 от 15.03.2024"):
        out = _mask(src)
        assert "{{DOCREF_" in out, f"не распознано: {src}"


def test_number_confirmed_once_is_masked_everywhere():
    """Тот же номер ниже стоит без якорного слова и оставался открытым.

    В акте это "маркетплейса ... Маркета № 6733498/23": рядом "Маркета", а не
    "договор", и повторное вхождение уходило в обезличенный документ.
    """
    text = ("в рамках заявления-оферты № 7777777/23 от 26.02.2023\n"
            "услуг маркетплейса Маркета № 7777777/23 от 26.02.2023")
    out = _mask(text)
    assert "7777777/23" not in out, "второе вхождение осталось открытым"


def test_date_written_in_words():
    """"от 16 декабря 2024 года" - в договорах так пишут чаще, чем цифрами."""
    out = _mask("Договор № АБ-000152 от 16 декабря 2024 года")
    assert "16 декабря 2024" not in out
    assert "{{DATE_1}}" in out


def test_long_phrase_between_anchor_and_number():
    """"Договору возмездного оказания услуг от № АБ-000152" - вставка длинная.

    Прежняя граница в два коротких слова теряла тут не только дату, но и сам
    номер: правило не срабатывало целиком.
    """
    out = _mask("Договору возмездного оказания услуг от № АБ-000152 от 16 декабря 2024 года")
    assert "АБ-000152" not in out and "16 декабря 2024" not in out


def test_amount_after_anchor_is_not_a_number():
    """Сумма после слова "договор" - не номер договора.

    Длинная вставка открывает дорогу ложным срабатываниям, поэтому без "№"
    номер обязан быть непохож на сумму: содержать букву или разделитель.
    """
    src = "Договор был заключен на сумму 150000 рублей"
    assert _mask(src) == src


def test_bare_digits_with_number_sign_still_work():
    """Со знаком номера чистым цифрам верим: "Счет-фактура № 74255758"."""
    assert "{{DOCREF_" in _mask("Счет-фактура № 11111111 от 31.07.2026")
