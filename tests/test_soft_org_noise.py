"""Чистка находок NER в мягком режиме (резюме).

Мягкий режим находит работодателей, но вместе с ними тащит мусор: обрывки с
плюсами и слэшами ("PERT + WBS", "Ромашка/Vasilek НЕ"), русские слова капсом из
заголовков ("РЕШЕНИЕ", "ОТКЛОНЕНА") и названия инструментов. Замер на живом
резюме 28.09.2026: 62 находки, настоящих организаций около 25.

Маска вместо термина не утечка, но документ становится нечитаем ни человеком,
ни моделью - ровно то, ради чего строгий режим и вводили.
"""
from pii_mask.core import Masker


def mask(text, **kw):
    return Masker(types=("ORG", "PERSON"), **kw).mask(text)[0]


def test_span_with_plus_or_slash_is_dropped():
    out = mask("Планирую в PERT + WBS и сравниваю Ромашка/Василек НЕ по срокам")
    assert "{{ORG" not in out, out


def test_russian_word_in_caps_is_not_a_company():
    """Заголовки в резюме пишут капсом: РЕШЕНИЕ, ОТКЛОНЕНА, ПРОЕКТОВ."""
    out = mask("РЕШЕНИЕ: заявка ОТКЛОНЕНА. Сдано ПРОЕКТОВ: 12")
    assert "{{ORG" not in out, out
    assert "{{PERSON" not in out, out


def test_tools_are_not_employers():
    out = mask("Инструменты: Obsidian, SQLite, Codex, Qwen, KTalk и LinkedIn")
    assert "{{ORG" not in out, out


def test_real_employer_survives_the_cleanup():
    """Чистка не должна съесть то, ради чего мягкий режим включали."""
    out = mask("2014-2025, Ромашка Групп - руководитель отдела развития")
    assert "{{ORG" in out, out


def test_confirmed_org_token_closes_its_repeats():
    """Название, подтвержденное хоть где, закрывается по всему документу.

    На живом резюме работодатель был найден один раз - в составе более длинного
    спана ("Ромашка NDA-блок"), - а двадцать семь остальных вхождений остались
    открытыми. Тот же прием уже работает для фамилий и для реквизитов.
    """
    text = ('ООО "Ромашка" NDA-блок: детали проектов под соглашением.\n'
            "В Ромашке выстроил процесс приемки.\n"
            "Опыт Ромашка: портфель из 16 проектов.")
    out = mask(text)
    assert "Ромашка" not in out, out
    assert "Ромашке" not in out, out


def test_short_abbreviation_repeat_is_closed():
    """Аббревиатура, расшифрованная в документе, закрывается и там, где стоит одна.

    В резюме работодатель представлен полным названием с аббревиатурой в
    скобках, а дальше по тексту идет только аббревиатура - в том числе внутри
    перечисления через слэш.
    """
    text = ('АНО "Агентство новых инициатив" (АНИ) - место работы.\n'
            "Партнеры: АНИ, Ромашка и другие.")
    out = mask(text)
    assert "АНИ" not in out, out


def test_latin_twin_in_brackets_is_closed():
    """Название дублируют латиницей в скобках: "Ромашка (Romashka)"."""
    text = ('ООО "Ромашка" (Romashka) - основное место работы.\n'
            "Опыт в Ромашке: пять лет.")
    out = mask(text)
    assert "Romashka" not in out, out


def test_business_abbreviations_are_not_companies():
    """ТМЦ, ПТО, ЕГРЮЛ - термины делопроизводства, а не места работы.

    На резюме бухгалтера они уходили в маски и делали обязанности нечитаемыми:
    "учет {{ORG_2}}" вместо "учет ТМЦ".
    """
    out = mask("Учет ТМЦ и первички, сметы от ПТО, выписки из ЕГРЮЛ и ЕГРИП")
    assert "{{ORG" not in out, out


def test_duty_phrase_is_not_a_company():
    """Обязанность начинается с отглагольного существительного, название - нет."""
    out = mask("Организация движения и учета документов. Полное ведение участка.")
    assert "{{ORG" not in out, out


def test_multiword_company_survives():
    """Чистка не должна съесть название из нескольких слов со строчными."""
    out = mask("Московский Государственный Университет пищевых продуктов, 1998")
    assert "{{ORG" in out, out


def test_verb_at_the_start_is_not_a_company():
    """Строка обязанностей начинается с глагола: "Автоматизировал...", "Запускал..."

    В колоночной верстке PDF такие строки NER регулярно метит организацией
    целиком, и в маску уходит достижение вместе с глаголом.
    """
    out = mask("- Автоматизировал блок адаптации и назначение целей\n"
               "- Запускал образовательные проекты под ключ")
    assert "{{ORG" not in out, out
