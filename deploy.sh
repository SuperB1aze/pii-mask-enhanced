#!/usr/bin/env bash
# Развернуть pii-mask в боевой каталог из текущего коммита.
#
# Зачем отдельный каталог, а не запуск из репозитория. В рабочем дереве идет
# разработка: незакоммиченная правка, переключенная ветка, мутационная проверка
# теста - все это меняло бы поведение боевого маскировщика прямо во время
# работы. 28.09.2026 так и было: правки и мутации шли в том же дереве, из
# которого бот маскирует присланные файлы.
#
# Демона нет намеренно (решение dwl 28.09.2026): сервисом пользуются нечасто,
# и процесс, поднимаемый на каждый вызов, не может протухнуть - в отличие от
# HTTP-шлюза, который месяц работал из уже удаленного каталога.
set -euo pipefail

SRC="$(cd "$(dirname "$0")" && pwd)"
PROD="${PII_MASK_HOME:-/data/apps/pii-mask}"
LINK="$HOME/.local/bin/pii-mask"

cd "$SRC"

# Гейт: боевой каталог не обновляется с красными тестами. Без этой проверки
# деплой - просто копирование, и сломанный маскировщик уезжает в бой молча.
echo "== тесты =="
.venv/bin/python -m pytest -q

DIRTY="$(git status --porcelain)"
if [ -n "$DIRTY" ]; then
    echo "!! в дереве есть незакоммиченные правки - они НЕ попадут в бой:" >&2
    echo "$DIRTY" >&2
fi
COMMIT="$(git rev-parse --short HEAD)"
BRANCH="$(git rev-parse --abbrev-ref HEAD)"

# В бой едет КОММИТ, а не дерево. Прежняя редакция обещала это строкой выше, а
# ставила из рабочего дерева - pip собирает пакет из файлов, а не из истории,
# так что незакоммиченные правки уезжали в бой, и предупреждение врало.
STAGE="$(mktemp -d)"
trap 'rm -rf "$STAGE"' EXIT
git archive HEAD | tar -x -C "$STAGE"

echo "== установка в $PROD =="
mkdir -p "$PROD"
[ -x "$PROD/.venv/bin/python" ] || python3 -m venv "$PROD/.venv"
# Не editable: в бой едет копия кода, а не ссылка на рабочее дерево - иначе
# разделение существует только на бумаге.
"$PROD/.venv/bin/pip" install --quiet --upgrade "$STAGE"

printf '%s %s %s\n' "$COMMIT" "$BRANCH" "$(date +%Y-%m-%dT%H:%M)" > "$PROD/ВЕРСИЯ"
mkdir -p "$(dirname "$LINK")"
ln -sfn "$PROD/.venv/bin/pii-mask" "$LINK"

echo "== проверка =="
# Спрашиваем у самой точки входа, какой код она импортирует, и делаем это ВНЕ
# каталога репозитория: стоя в нем, python подхватывает рабочее дерево, и
# проверка отвечает "все в бою" для обоих состояний - исправного и нет.
# Первая версия этого скрипта проверяла именно так и врала.
GOT="$(cd /tmp && "$LINK" where)"
case "$GOT" in
    "$PROD"/*) ;;
    *) echo "!! точка входа импортирует код не из боевого каталога: $GOT" >&2
       exit 1 ;;
esac
echo "код в бою: $GOT"
echo "версия: $(cat "$PROD/ВЕРСИЯ")"
echo "точка входа: $LINK -> $(readlink -f "$LINK")"
